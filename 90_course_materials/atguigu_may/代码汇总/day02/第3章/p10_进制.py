"""
    1、进制：
    （1）十进制，数字范围[0,9]，进位规则：逢十进一
        在程序中，正常表示数字即可
    （2）二进制，数字范围[0,1]，进位规则：逢二进一
        在程序中，在数字前面0B 或 0b
    （3）八进制，数字范围[0,7]，进位规则：逢八进一
        在程序中，在数字前面0o 或  0O(大写o）
    （4）十六进制，数字范围[0,9][A,F]，进位规则：逢十六进一
        在程序中，在数字前面0X 或 0x
    十进制   二进制
    0       0
    1       1
    2       10
    3       11
    4       100
    。。。
"""
#数字： 101010
print("十进制101010：", 101010)
print("二进制101010：", 0B101010)
print("八进制101010：", 0o101010)
print("十六进制101010：", 0X101010)
"""
显示结果：都是十进制结果
十进制101010： 101010
二进制101010： 42
八进制101010： 33288
十六进制101010： 1052688
"""

#数字：856
