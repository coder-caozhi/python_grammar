"""
    2、各种进制如何换算
    人工算（了解）
    （1）十进制->二进制
        除2倒取余
    （2）二进制 -> 十进制
        权值相加法，从右往左依次是2的0次，1次，...
    （3）十进制 -> 八进制
        除8倒取余
    （4）八进制 -> 十进制
        权值相加法，从右往左依次是8的0次，1次，...
    。。。。
    
    计算器（能使用）
"""
num = 25
print("十进制：",num)
print("二进制：",bin(num))
print("八进制：",oct(num))
print("十六进制：",hex(num))
"""
显示结果：
十进制： 25
二进制： 0b11001
八进制： 0o31
十六进制： 0x19
"""

