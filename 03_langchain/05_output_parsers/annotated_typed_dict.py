# 阅读路线：定义别名 → TypedDict → 构造普通字典 → 输出 188
# 当前代码要注意：原说明称运行时会检查 int 并不准确：本例连 int 类型也不会自动检查
# 动手验证：传入字符串 age2，与 annotated_pydantic 的校验对比
