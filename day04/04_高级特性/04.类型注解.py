# =====================================================================
# 04. 类型注解（Type Hints）
# ---------------------------------------------------------------------
# 【重要】类型注解只是"给人看 + 给 IDE 提示"，Python 运行时不会校验！
#         写 age: int = "abc" 也不会报错，只是 IDE 会标黄警告
#         真正想校验数据，要用 05.测试数据校验神器.py 里的 pydantic
# 【语法】变量名: 类型 = 值
# 【两种写法】容器类注解
#     list[str] / dict[str, int]     → Python 3.9+ 的现代简写
#     List[str] / Dict[str, int]     → typing 模块的传统写法（都行）
# 【联合类型】表示"可能是 A 也可能是 B"
#     str | None        → Python 3.10+ 现代简写
#     Optional[str]     → typing 传统写法（等价）
#     Union[str, None]  → 同样等价
# =====================================================================

from typing import List, Dict, Optional, Union, Any


# ---------------------------------------------------------------------
# 一、基本类型注解
# ---------------------------------------------------------------------
print("=" * 40)
print("一、基本类型")
print("=" * 40)

name: str = "王飞龙"
print(name)                       # 输出：王飞龙

age: int = 24
print(age)                        # 输出：24


# ---------------------------------------------------------------------
# 二、容器类型注解
# ---------------------------------------------------------------------
print("=" * 40)
print("二、容器类型")
print("=" * 40)

# 现代简写：直接用小写 list[...]
hobby: list[str] = ["男", "打台球", "唱歌"]
print(hobby)                      # 输出：['男', '打台球', '唱歌']

# 传统写法：从 typing 导入 List，用大写 List[...]
girl_friends: List[str] = ["a", "b", "c"]
print(girl_friends)               # 输出：['a', 'b', 'c']

# 字典要写"键和值"两个类型
score: Dict[str, float] = {
    "java": 88.88,
    "python": 66.66
}
print(score)                      # 输出：{'java': 88.88, 'python': 66.66}


# ---------------------------------------------------------------------
# 三、联合类型：可能是 A，也可能是 B（含 None）
# ---------------------------------------------------------------------
print("=" * 40)
print("三、联合类型")
print("=" * 40)

# 下面三行表达的意思完全一样："gender 要么是字符串，要么是 None"
# 这里连写三遍是为了让你看出它们只是"不同年代的写法"而已，
# 实际写代码时挑一种就好，通常用最上面的现代简写
gender: str | None = None             # Python 3.10+ 的现代简写
gender: Optional[str] = None          # typing 里的传统写法
gender: Union[str, None] = None       # Union 写法，同样等价

email: Optional[str] = "wangfeilong@qq.com"
print(email)                      # 输出：wangfeilong@qq.com

# 不只是与 None 联合，任意类型之间都能联合
salary: int | float = 88888
print(salary)                     # 输出：88888

address: Union[str, list] = "宏福苑"
print(address)                    # 输出：宏福苑


# ---------------------------------------------------------------------
# 四、Any：放弃类型检查（"什么类型都行"）
# ---------------------------------------------------------------------
print("=" * 40)
print("四、Any")
print("=" * 40)

# Any 表示"不限制"，一般用在类型真的说不清的地方。
# 注意：变量名 id 会覆盖内置函数 id()，实际开发中要避免这么命名
id: Any = 110001201901010019
print(id)                         # 输出：110001201901010019


# ---------------------------------------------------------------------
# 五、类型注解的最佳用法：写在函数签名上
# ---------------------------------------------------------------------
#   函数参数注解 + 返回值注解才是最容易体现价值的地方，例如：
#
#       def add(a: int, b: int) -> int:
#           return a + b
#
#   好处：
#     1. IDE 能给出参数提示、自动补全、错误高亮
#     2. 别人（包括三个月后的你）一眼看懂接口约定
#     3. 配合 mypy / pydantic 可以做静态检查或运行时校验
