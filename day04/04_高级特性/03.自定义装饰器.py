# =====================================================================
# 03. 自定义装饰器
# ---------------------------------------------------------------------
# 【本质】就是一个函数：接收一个函数，返回一个新函数
# 【作用】在不修改原函数代码的前提下，"包一层"扩展它的功能
#         （典型场景：打日志、计时、鉴权、重试、缓存）
# 【语法糖】@装饰器名 写在函数定义上面，等价于 add = record_logging(add)
# 【必加】@functools.wraps(fun)
#         否则原函数的名字、文档注释会被 wrapper 覆盖掉
# =====================================================================

import functools


# ---------------------------------------------------------------------
# 一、定义装饰器
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义装饰器")
print("=" * 40)


def record_logging(fun):
    """给被装饰的函数加上"开始/结束"的日志"""

    # functools.wraps 把原函数的 __name__、__doc__ 等复制到 wrapper 上
    # 不加这行的话，add.__name__ 会变成 "wrapper"
    @functools.wraps(fun)
    def wrapper(*args, **kwargs):
        # *args / **kwargs：原函数有几个参数、是什么类型，这里都能原样接收
        #                  这样装饰器才能"通吃"所有函数
        print(f"{fun.__name__}开始了，传入的参数是：{args}或者{kwargs}")

        # 调用原函数，拿到真正的计算结果
        rest = fun(*args, **kwargs)

        print(f"{fun.__name__}返回了结果：{rest}")

        # 一定要把结果 return 出去，否则外面拿到的是 None
        return rest

    # 返回"包装后的新函数"
    return wrapper


# ---------------------------------------------------------------------
# 二、使用装饰器（@ 语法糖）
# ---------------------------------------------------------------------
print("=" * 40)
print("二、使用装饰器")
print("=" * 40)


@record_logging
def add(a, b):
    """
        这是一个求和的函数
    :param a: 第一个参数
    :param b: 第二个参数
    :return: 两个参数的和
    """
    return a + b


@record_logging
def sub(a, b):
    return a - b


# 上面这两段写法，完全等价于：
#     def add(a, b): ...
#     add = record_logging(add)
# 可见 @ 只是"调用装饰器并重新赋值"的简写


# ---------------------------------------------------------------------
# 三、调用被装饰的函数
# ---------------------------------------------------------------------
print("=" * 40)
print("三、调用函数")
print("=" * 40)

result = add(10, 2)
# 输出：add开始了，传入的参数是：(10, 2)或者{}
#       add返回了结果：12

result2 = sub(10, 2)
# 输出：sub开始了，传入的参数是：(10, 2)或者{}
#       sub返回了结果：8

print(f"add 的结果是：{result}")       # 输出：12
print(f"sub 的结果是：{result2}")      # 输出：8


# ---------------------------------------------------------------------
# 四、验证 functools.wraps 的作用
# ---------------------------------------------------------------------
print("=" * 40)
print("四、wraps 的作用")
print("=" * 40)

print(add.__name__)     # 有 wraps → 输出：add；去掉 wraps 会变成 wrapper
print(add.__doc__)      # 有 wraps → 还能看到原来的文档注释


