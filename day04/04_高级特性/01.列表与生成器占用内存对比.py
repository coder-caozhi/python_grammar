# =====================================================================
# 01. 列表与生成器 —— 内存占用对比
# ---------------------------------------------------------------------
# 【列表推导式】[i for i in range(n)] → 立刻把所有元素算出来存进内存
# 【生成器表达式】(i for i in range(n)) → 只记住"怎么算"，用一个算一个
# 【核心区别】列表 = 拿空间换方便；生成器 = 拿时间换空间
# 【副作用】生成器是"一次性"的：遍历过后就空了，不能重复遍历
# =====================================================================

import sys


# ---------------------------------------------------------------------
# 一、列表：一次性把所有数据装进内存
# ---------------------------------------------------------------------
print("=" * 40)
print("一、列表的内存占用")
print("=" * 40)

my_list = [i for i in range(1000000)]     # 100 万个数字
# print(my_list)                          # 内容太多，别打印

print(f"列表占用的字节数：{sys.getsizeof(my_list)}")
# 输出：8448728（约 8 MB）—— 元素越多，占得越多


# ---------------------------------------------------------------------
# 二、生成器：几乎不占内存
# ---------------------------------------------------------------------
print("=" * 40)
print("二、生成器的内存占用")
print("=" * 40)

# 注意：外面是"小括号"，不是中括号 —— 这就是生成器表达式
my_generator = (i for i in range(1000000))
print(my_generator)
# 输出：<generator object <genexpr> at 0x...> ← 只是一个"生成器对象"

print(f"生成器占用的字节数：{sys.getsizeof(my_generator)}")
# 输出：200（约 200 字节）—— 和元素个数无关，因为它并不存元素！

# 结论：同样面对 100 万个数字，内存差了约 4 万倍


# ---------------------------------------------------------------------
# 三、生成器只能"往前走"，用 next() 一个一个取
# ---------------------------------------------------------------------
print("=" * 40)
print("三、用 next() 取值")
print("=" * 40)

print(next(my_generator))     # 输出：0
print(next(my_generator))     # 输出：1
print(next(my_generator))     # 输出：2
print(next(my_generator))     # 输出：3
# 每取一次，生成器就"往前走一步"，取值不会被重置

# 注意：这里的 range 是 1000000，所以不会像下面注释说的那样报错。
#       只有写成 (i for i in range(4)) 时，取第 5 次才会：
#       StopIteration —— 元素取完了
print(next(my_generator))     # 输出：4


# ---------------------------------------------------------------------
# 四、接着用 for 遍历（从上次停下的位置继续）
# ---------------------------------------------------------------------
print("=" * 40)
print("四、继续遍历")
print("=" * 40)

first_value = None
last_value = None

for i in my_generator:
    if first_value is None:
        first_value = i          # 第一次进来时记录，之后就再也不改了
    last_value = i               # 每次覆盖，循环结束后就是最后一个值

print(f"剩余部分第一个值：{first_value}")     # 输出：5（前面 0~4 已经被 next 取走了）
print(f"剩余部分最后一个值：{last_value}")    # 输出：999999


# ---------------------------------------------------------------------
# 五、对比小结
# ---------------------------------------------------------------------
#                 列表                        生成器
#   ----------------------------------------------------------------
#   写法        [x for x in ...]            (x for x in ...)
#   求值时机    立刻全部算完                 用到才算（惰性求值）
#   内存        随元素个数增长               固定一小块
#   可重复遍历  可以（多次 for 都没问题）      不可以（一次性的）
#   支持下标    可以 list[0]               不可以
#   适用场景    需要反复访问、需要随机取值     数据量大、只顺序过一遍
