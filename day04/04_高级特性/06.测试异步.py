# =====================================================================
# 06. 测试异步（asyncio）
# ---------------------------------------------------------------------
# 【要解决的问题】IO 等待（网络请求、数据库查询、读文件）时 CPU 其实在闲着
# 【同步】一个接一个做完 → 3 个任务各等 1 秒，总共约 3 秒
# 【异步】等待时切去做别的 → 3 个任务同时等，总共约 1 秒
# 【两个关键字】
#     async def  → 声明"协程函数"，调用它得到的是协程对象，不会立刻执行
#     await      → 在这里"让出"控制权，去做别的任务，等结果回来再继续
# 【三个配套函数】
#     asyncio.run(协程)                  → 启动事件循环（程序入口，最外层用）
#     asyncio.gather(协程1, 协程2, ...)  → 并发跑一批，等全部完成后返回结果列表
#     asyncio.sleep(n)                   → 异步版 time.sleep，不阻塞事件循环
# =====================================================================

import asyncio
import time


# ---------------------------------------------------------------------
# 一、异步版：模拟耗时 IO 操作
# ---------------------------------------------------------------------
async def download_url(url: str):
    """异步下载 URL（非阻塞）"""
    print(f"开始下载: {url}")
    # 这里的 await 很关键：等待 1 秒的过程中，事件循环会去处理其它任务
    await asyncio.sleep(1)
    print(f"下载完成: {url}")
    return f"{url} 数据"


# ---------------------------------------------------------------------
# 二、同步版：同样的功能，但它会"卡住"
# ---------------------------------------------------------------------
def sync_download_url(url: str):
    """同步下载 URL（阻塞）"""
    print(f"开始下载: {url}")
    # time.sleep 会真的把整个程序卡住 1 秒，CPU 干等着
    time.sleep(1)
    print(f"下载完成: {url}")
    return f"{url} 数据"


# ---------------------------------------------------------------------
# 三、异步主函数
# ---------------------------------------------------------------------
async def async_main():
    start = time.time()

    # 创建协程列表。注意：此时它们还没有开始执行
    tasks = [
        download_url("http://baidu.com"),
        download_url("http://google.com"),
        download_url("http://python.org")
    ]

    # gather 会把它们全部注册进事件循环，并发执行
    # 总耗时 ≈ 1 秒（最慢的那个），而不是 3 秒
    results = await asyncio.gather(*tasks)

    end = time.time()
    print(f"\n异步总耗时: {end - start:.2f} 秒")
    print("异步结果:", results)


# ---------------------------------------------------------------------
# 四、同步主函数
# ---------------------------------------------------------------------
def sync_main():
    start = time.time()

    # 串行：必须等第一个完成，才能开始第二个 → 总耗时 ≈ 3 秒
    results = [
        sync_download_url("http://baidu.com"),
        sync_download_url("http://google.com"),
        sync_download_url("http://python.org")
    ]

    end = time.time()
    print(f"\n同步总耗时: {end - start:.2f} 秒")
    print("同步结果:", results)


# ---------------------------------------------------------------------
# 五、运行对比
# ---------------------------------------------------------------------
if __name__ == "__main__":
    print("=== 异步执行 ===")
    asyncio.run(async_main())         # 事件循环的唯一入口，只在最外层调用一次

    print("\n=== 同步执行 ===")
    sync_main()


# 实际输出：
