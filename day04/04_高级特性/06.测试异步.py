# 开始下载: http://baidu.com
# 开始下载: http://google.com
# 开始下载: http://python.org          ← 三个"开始"先一起打印出来
# 下载完成: http://baidu.com
# 下载完成: http://google.com
# 下载完成: http://python.org
#
# 异步总耗时: 1.01 秒                  ← 约 1 秒
# 异步结果: ['http://baidu.com 数据', 'http://google.com 数据', 'http://python.org 数据']
#
# === 同步执行 ===
# 开始下载: http://baidu.com
# 下载完成: http://baidu.com           ← 开始/完成是成对出现的
# 开始下载: http://google.com
# 下载完成: http://google.com
# 开始下载: http://python.org
# 下载完成: http://python.org
#
# 同步总耗时: 3.00 秒                  ← 约 3 秒
# 同步结果: ['http://baidu.com 数据', 'http://google.com 数据', 'http://python.org 数据']


# ---------------------------------------------------------------------
# 六、几个必须记住的点
# ---------------------------------------------------------------------
#   1. await 只能在 async def 里面用
#   2. asyncio.run() 只能调一次，且必须在最外层（不能嵌套在已有事件循环里）
#   3. async def 定义的函数，不加 await 直接调用，什么都不会发生
#         download_url("http://x.com")          ← 只是创建了协程，没执行
#         await download_url("http://x.com")    ← 这才真正执行
#   4. 异步不是"并行计算"，它解决的是"IO 等待"。
#      CPU 密集（比如大量数学运算）的任务，异步帮不上忙，要用多进程
