# =====================================================================
# 02. 自定义生成器（yield）
# ---------------------------------------------------------------------
# 【yield 的作用】让函数"暂停并交出一个值"，下次再从这里继续跑
# 【和 return 的区别】
#     return → 函数直接结束，只返回一次
#     yield  → 函数挂起，可以返回很多次，直到函数体跑完
# 【判定规则】函数体里只要有 yield，调用它就不再执行函数体，
#             而是返回一个"生成器对象"
# 【应用】range 就是典型例子，本文件手写一个 my_range 来体会原理
# =====================================================================


# ---------------------------------------------------------------------
# 一、自定义一个生成器，产出 1 到 n
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义生成器")
print("=" * 40)


def my_range(n):
    """模仿内置 range(n)，产出 1, 2, ..., n"""
    i = 1
    while i <= n:
        # 执行到 yield 时：
        #   1. 把当前 i 的值"交出去"
        #   2. 函数在这里暂停，冻结所有变量
        # 下次调用 next() 时，从这行的下一句继续跑
        yield i
        i += 1


# ---------------------------------------------------------------------
# 二、调用生成器函数
# ---------------------------------------------------------------------
print("=" * 40)
print("二、调用生成器函数")
print("=" * 40)

# 注意：这里并没有执行函数体！只是拿到了一个"生成器对象"
my_num = my_range(5)
print(my_num)
# 输出：<generator object my_range at 0x...>


# ---------------------------------------------------------------------
# 三、一个值一个值地取
# ---------------------------------------------------------------------
print("=" * 40)
print("三、用 next() 逐个取值")
print("=" * 40)

print(next(my_num))     # 输出：1（跑到第一个 yield，交出 1 后暂停）
print(next(my_num))     # 输出：2（从 i += 1 继续，再循环到 yield）
print(next(my_num))     # 输出：3
print(next(my_num))     # 输出：4
print(next(my_num))     # 输出：5
# print(next(my_num))   # 输出：抛 StopIteration —— 函数体跑完了，没有更多值了
                         #（这个异常被 for 循环自动处理，所以 for 不会报错）


# ---------------------------------------------------------------------
# 四、执行顺序图解（以取到 3 为例）
# ---------------------------------------------------------------------
#   i = 1  → while 成立 → yield 1（暂停）→ next() 唤醒 → i = 2
#   循环   → yield 2（暂停）→ next() 唤醒 → i = 3
#   循环   → yield 3（暂停）...
#
#   关键：每调用一次 next，函数只跑到"下一个 yield"就停，
#         而不是像普通函数那样一口气跑完


