# ---------------------------------------------------------------------
# 一、自定义异常：带上错误码和提示信息
# ---------------------------------------------------------------------
print("=" * 40)
print("一、自定义异常")
print("=" * 40)


class LoginError(Exception):

    def __init__(self, code, message):
        # 注意：这里没有调用 super().__init__(message)
        #      所以下面 __str__ 必须自己定义，否则打印出来的是空信息
        self.code = code              # 业务错误码，方便调用方区分原因
        self.message = message        # 给用户看的提示

    def __str__(self):
        """相当于 Java 的 toString，决定 print(异常对象) 时的样子"""
        return f"LoginError(code={self.code}, message={self.message})"


# ---------------------------------------------------------------------
# 二、登录函数
# ---------------------------------------------------------------------
print("=" * 40)
print("二、登录函数")
print("=" * 40)


def login(username, password):
    try:
        # 判断用户名是否存在
        if "admin" != username:
            # 抛出异常：错误码 6001
            raise LoginError(6001, "用户不存在")

        # 判断密码是否正确
        if "123456" != password:
            # 抛出异常：错误码 6002
            raise LoginError(6002, "密码不正确")
    except LoginError as e:
        # 精确捕获自定义异常，打印错误码和提示
        print(f"登录失败：{e}")
    else:
        # 走到这里说明上面两个 try 都没抛异常 → 登录成功
        print("登录成功")
    finally:
        # 无论成功失败都要释放资源
        print("登录流程结束，释放连接")


