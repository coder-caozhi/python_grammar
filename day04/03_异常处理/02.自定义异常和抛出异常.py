# =====================================================================
# 02. 自定义异常 和 抛出异常
# ---------------------------------------------------------------------
# 【raise】  手动抛出异常，语法：raise 异常类型("提示信息")
# 【自定义】让类继承 Exception 就成为一个异常类
#            class LoginError(Exception): ...
# 【为什么自定义】内置异常表达不了业务含义。
#                 比如"用户不存在"用 ValueError 也能凑合，
#                 但 LoginError 一眼就能看出是登录业务的问题
# 【技巧】自定义异常里通常还会带"错误码"，方便前端/调用方判断具体原因
# =====================================================================


# ---------------------------------------------------------------------
# 一、最简单的自定义异常
# ---------------------------------------------------------------------
print("=" * 40)
print("一、最简单的自定义异常")
print("=" * 40)


class LoginError(Exception):
    """自定义异常：什么都不用写，继承 Exception 即可"""
    pass


# ---------------------------------------------------------------------
# 二、手动抛出异常并捕获
# ---------------------------------------------------------------------
print("=" * 40)
print("二、抛出并捕获异常")
print("=" * 40)

try:
    # 抛一个内置异常（把下面这行的注释打开试试）
    # raise ZeroDivisionError("出现了除0的异常")

    # 抛一个自定义异常
    raise LoginError("出现了自定义异常")
except Exception as e:
    # 父类 Exception 可以捕获所有子类异常，所以这里能抓到 LoginError
    print(f"出现了异常，异常信息是：{e}")
finally:
    print("程序执行结束")

# 输出：
#   出现了异常，异常信息是：出现了自定义异常
#   程序执行结束


# ---------------------------------------------------------------------
# 三、关键结论
# ---------------------------------------------------------------------
#   1. raise 之后，当前函数的剩余代码不再执行（相当于"立刻中断"）
#   2. 抛出的异常必须有地方接住，否则程序会直接崩掉并打印 traceback
#   3. 捕获时写父类 Exception，能接住所有子类异常
#      —— 但精确捕获（写 LoginError）更利于区分处理，见 03.小练习.py
