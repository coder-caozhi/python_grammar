# =====================================================================
# 03. 小练习 —— 统计文件的行数和某个字出现的次数
# ---------------------------------------------------------------------
# 【需求】统计 test2.txt 一共多少行，以及"忙"字出现了多少次
# 【思路】一行一行遍历：
#            每读一行  → 行数 +1
#            用 line.count("忙") 数出这一行里的个数 → 累加
# 【要点】str.count(子串) 是"数这个子串在本字符串里出现几次"，
#         它比手写循环更简洁
# =====================================================================

# ---------------------------------------------------------------------
# 一、读取文件并统计
# ---------------------------------------------------------------------
print("=" * 40)
print("一、统计结果")
print("=" * 40)

with open("test2.txt", mode="r", encoding="utf-8") as f:
    line_count = 0                    # 行数计数器
    word_count = 0                    # "忙"字出现次数计数器

    for line in f:
        # 每循环一次就代表读到了一行
        line_count += 1

        # 统计当前行里有多少个"忙"，再累加到总数上
        word_count += line.count("忙")

    print(f"文件的行数是：{line_count}")
    print(f"'忙'字出现的次数是：{word_count}")


# ---------------------------------------------------------------------
# 二、拆解说明
# ---------------------------------------------------------------------
# 1. 行数是"按换行符 \n 数出来的"
#    文件里有多少个 \n，for 循环就会走多少遍。
#    注意：空行（只有一个 \n）也算一行，所以有空行的文件行数会比你看到的多。
#
# 2. "忙"为什么会重复计数？
#    count 是"精确匹配子串"，下面这几行各自贡献了若干个：
#        蝴蝶儿忙，蜜蜂也忙        → 2 个
#        小鸟儿忙着，白云也忙      → 2 个（"忙着"里的"忙"也算进去）
#        只因为相遇太忙            → 1 个
#    累加起来，当前文件里一共 5 个。
#
# 3. 想只统计"忙"作为独立词出现、不算"忙着"这种，怎么办？
#    这时就得用正则了：re.findall(r"忙(?!着)", line)
#
# 4. 友情提示：test2.txt 是 02.写文件.py 用追加模式写出来的，
#    每运行一次追加写，行数和"忙"的个数都会再增加，
#    所以这里的 9 和 5 只是"当前文件状态"的结果。
