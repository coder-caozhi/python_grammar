# ---------------------------------------------------------------------
# 四、补充：三种遍历文件的方式
# ---------------------------------------------------------------------
#   f.read()            → 一次性读成"一个字符串"，小文件用
#   f.readlines()       → 一次性读成"一个列表"，每行一个元素
#   for line in f:      → 迭代器方式，读一行处理一行，最省内存 ✅ 推荐
#
#   另外 rstrip 和 strip 的区别：
#       line.strip()        → 去掉首尾的空白（包括空格、制表符、换行）
#       line.rstrip("\n")   → 只去掉尾部的换行符，保留行首缩进
