# =====================================================================
# 01. 读文件
# ---------------------------------------------------------------------
# 【标准写法】with open(路径, mode, encoding) as f:  → 用完自动关闭文件
# 【open 三个参数】
#     路径      → 文件在哪（相对路径以"当前运行目录"为基准）
#     mode      → "r" 只读 / "w" 覆盖写 / "a" 追加写 / "r+" 读写
#     encoding  → 固定写 "utf-8"，否则中文容易乱码
# 【读多少】
#     小文件 → f.read()          一次全读进来（返回一个字符串）
#     大文件 → for line in f     一行一行读（省内存，推荐）
# 【常见错误】文件不存在 → FileNotFoundError
# =====================================================================


# ---------------------------------------------------------------------
# 一、读小文件：一次全部读进来
# ---------------------------------------------------------------------
print("=" * 40)
print("一、读小文件")
print("=" * 40)


def read_small_file(file_path, mode, encoding):
    # with 会在代码块结束时自动 f.close()，不用担心忘了关
    with open(file_path, mode=mode, encoding=encoding) as f:
        content = f.read()            # 一次读出全部内容（字符串）
        print(content)
        print(f"读到的类型是：{type(content)}")     # 输出：<class 'str'>


# ---------------------------------------------------------------------
# 二、读大文件：一行一行读（省内存）
# ---------------------------------------------------------------------
print("=" * 40)
print("二、读大文件")
print("=" * 40)


def read_big_file(file_path, mode, encoding):
    with open(file_path, mode=mode, encoding=encoding) as f:
        # 直接 for line in f 比 f.readlines() 更省内存：
        # readlines() 会把所有行一次性装进一个列表
        for line in f.readlines():
            # 每行末尾自带换行符，print 又加一个 → 会多出空行
            # 所以先 rstrip 去掉它
            line_strip = line.rstrip("\n")
            print(line_strip)


# ---------------------------------------------------------------------
# 三、调用
# ---------------------------------------------------------------------
print("=" * 40)
print("三、调用")
print("=" * 40)

# 读小文件：把 test.txt 整体读出来
