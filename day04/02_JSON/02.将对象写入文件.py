# =====================================================================
# 02. 将对象写入 JSON 文件 / 从文件读取
# ---------------------------------------------------------------------
# 【四个函数配对记】
#     json.dumps / json.loads   → 操作"字符串"（s = string）
#     json.dump  / json.load    → 操作"文件"（没有 s，直接给文件对象）
# 【两个常用参数】
#     ensure_ascii=False → 保留中文（默认 True 会把中文转成 \uXXXX）
#     indent=4           → 格式化缩进，便于阅读/调试
# 【注意】文件必须用 encoding='utf-8' 打开，否则中文会乱码
# =====================================================================

import json


# ---------------------------------------------------------------------
# 一、准备要写入的数据
# ---------------------------------------------------------------------
print("=" * 40)
print("一、准备数据")
print("=" * 40)

user_list = [
    {"name": "Tom", "age": 18, "city": "北京"},
    {"name": "Jerry", "age": 20, "city": "上海"},
    {"name": "Alice", "age": 19, "city": "广州"}
]

print(f"待写入的数据类型是：{type(user_list)}")     # 输出：<class 'list'>


# ---------------------------------------------------------------------
# 二、写入 JSON 文件（json.dump）
# ---------------------------------------------------------------------
print("=" * 40)
print("二、写入 JSON 文件")
print("=" * 40)

with open('python_data.json', 'w', encoding='utf-8') as f:
    # 关键参数：
    #   ensure_ascii=False → 保留中文（否则会变成 "\u5317\u4eac"）
    #   indent=4           → 缩进 4 个空格，格式化输出，方便人看
    #                        （生产环境可以省略，能减小文件体积）
    json.dump(user_list, f, indent=4, ensure_ascii=False)

print("写入完成，内容如下：")
with open('python_data.json', 'r', encoding='utf-8') as f:
    print(f.read())


# ---------------------------------------------------------------------
# 三、从 JSON 文件读取（json.load）
# ---------------------------------------------------------------------
print("=" * 40)
print("三、读取 JSON 文件")
print("=" * 40)

with open('python_data.json', 'r', encoding='utf-8') as f:
    data = json.load(f)
    print(data)
    # 输出：[{'name': 'Tom', 'age': 18, 'city': '北京'}, ...]
    print(f"读出来的类型是：{type(data)}")           # 输出：<class 'list'>

# 小结：JSON 数组读回来是 list，JSON 对象读回来是 dict


# ---------------------------------------------------------------------
# 四、dumps 和 dump 的区别（对着看就清楚了）
# ---------------------------------------------------------------------
#   json.dumps(obj)          → 返回字符串，你没给它文件
#   json.dump(obj, f)        → 没有返回值，它自己写进 f
#
#   json.loads(s)            → 传入字符串，返回 Python 对象
#   json.load(f)             → 传入文件对象，返回 Python 对象
