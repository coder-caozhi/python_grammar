# =====================================================================
# test.py —— 模块导入演示：完整导入 / 起别名 / 精确导入
# ---------------------------------------------------------------------
# 【方式一】import 模块            → 所有成员都能用，但要写"模块名.成员"
# 【方式二】import 模块 as 别名     → 用"别名.成员"访问
# 【方式三】from 模块 import 成员   → 直接用成员名，不用加前缀
# =====================================================================

# 完整导入：被导入模块中的所有成员都可以使用
import fun

# 完整导入并起别名
import fun as f

# 精确导入：只把 fun3 这个名字拿到当前文件
from fun import fun3


# ---------------------------------------------------------------------
# 一、通过"模块名.成员"访问变量
# ---------------------------------------------------------------------
print("=" * 40)
print("一、访问模块中的变量")
print("=" * 40)

print(fun.num)                    # 公共变量，输出：888
print(fun._my_str)                # 受保护的变量，输出：我是受保护的变量
print(fun.__my_str2)              # 私有变量（模块级不会改名），输出：我是一个私有变量


# ---------------------------------------------------------------------
# 二、通过"别名.成员"访问变量
# ---------------------------------------------------------------------
print("=" * 40)
print("二、通过别名访问")
print("=" * 40)

print(f.num)                      # 输出：888
print(f.PI)                       # 输出：3.1415926
print(f.fun3())


# ---------------------------------------------------------------------
# 三、调用被导入模块中的函数
# ---------------------------------------------------------------------
print("=" * 40)
print("三、调用模块中的函数")
print("=" * 40)

fun.fun()                         # 公共函数，输出：我是一个公共的函数
fun._fun1()                       # 受保护的函数，输出：我是一个受保护的函数
fun.__fun2()                      # 私有函数，输出：我是一个私有的函数


# ---------------------------------------------------------------------
# 四、调用精确导入的函数（直接用名字，不加模块名前缀）
# ---------------------------------------------------------------------
print("=" * 40)
print("四、调用精确导入的函数")
print("=" * 40)

fun3()                            # 输出：测试精确导入
