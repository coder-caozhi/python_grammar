# =====================================================================
# fun.py —— 被导入的模块
# ---------------------------------------------------------------------
# 【__all__】 限制 from fun import * 时能导入哪些成员
# 【命名约定】单下划线 = 受保护，双下划线 = 私有
#             （模块级别只是"约定"，并不会真正阻止访问）
# 【导入即执行】模块中的顶层代码在被导入时会自动执行（见文件末尾的 print）
# =====================================================================

# 限制 from fun import * 时，只导入 num 和 fun3 这两个成员
__all__ = ["num", "fun3"]


# ---------------------------------------------------------------------
# 一、模块中的变量
# ---------------------------------------------------------------------
num = 888                         # 公共变量
PI = 3.1415926                    # 常量（约定用全大写命名）
_my_str = "我是受保护的变量"       # 受保护的变量
__my_str2 = "我是一个私有变量"     # 私有的变量


# ---------------------------------------------------------------------
# 二、模块中的函数
# ---------------------------------------------------------------------
def fun():
    """公共函数"""
    print("我是一个公共的函数")


def _fun1():
    """受保护的函数"""
    print("我是一个受保护的函数")


def __fun2():
    """私有的函数"""
    print("我是一个私有的函数")


def fun3():
    """公共函数：用于演示"精确导入"和"import *" """
    print("测试精确导入")


# ---------------------------------------------------------------------
# 三、顶层代码：模块"被导入"时就会执行
# ---------------------------------------------------------------------
print("fun模块被导入了")
