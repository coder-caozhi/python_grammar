# =====================================================================
# test2.py —— 模块导入演示：from 模块 import *（局部导入）
# ---------------------------------------------------------------------
# 【语法】from 模块 import *
# 【限制】只会导入"公共成员"，以及 __all__ 中显式列出的成员
#         受保护(_x) 和私有(__x) 的成员不会被导入
# 【注意】当前 fun 模块的 __all__ = ["num", "fun3"]，
#         所以这里只能直接使用 num 和 fun3，其它成员都拿不到
# =====================================================================

from fun import *


# ---------------------------------------------------------------------
# 一、访问被导入的变量
# ---------------------------------------------------------------------
print("=" * 40)
print("一、访问被导入的变量")
print("=" * 40)

print(num)                        # 输出：888

# 以下成员不在 __all__ 中，import * 不会导入它们（放开注释会报 NameError）
# print(_my_str)
# print(__my_str2)


# ---------------------------------------------------------------------
# 二、调用被导入的函数
# ---------------------------------------------------------------------
print("=" * 40)
print("二、调用被导入的函数")
print("=" * 40)

# 同样不在 __all__ 中，import * 拿不到（放开注释会报 NameError）
# fun()
# _fun1()
# __fun2()

fun3()                            # 输出：测试精确导入
