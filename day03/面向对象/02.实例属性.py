# =====================================================================
# 02. 实例属性
# ---------------------------------------------------------------------
# 【定义位置】在 __init__ 中通过 self.xxx = 值 定义
# 【命名约定】name   → 公共属性（类似 Java 的 public）
#             _name  → 受保护属性（类似 Java 的 protected）
#             __name → 私有属性（类似 Java 的 private）
# 【私有属性】直接 实例.__name 访问会报错，
#             但可以用 实例._类名__属性名 强取（不推荐）
# =====================================================================


# ---------------------------------------------------------------------
# 一、定义类与三种实例属性
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义类")
print("=" * 40)

class Person:
    """这是一个Person类"""

    home = "earth"                # 类属性，所有实例共享

    def __init__(self, name, age, gender):
        self.name = name          # 公共属性，相当于 Java 中的 public
        self._age = age           # 受保护属性，相当于 Java 中的 protected
        self.__gender = gender    # 私有属性，相当于 Java 中的 private


# ---------------------------------------------------------------------
# 二、实例化并获取属性值
# ---------------------------------------------------------------------
print("=" * 40)
print("二、获取实例属性")
print("=" * 40)

p = Person("蔡徐坤", 27, "男")

print(p.name)                     # 公共属性，输出：蔡徐坤
print(p._age)                     # 受保护属性，能取到但"不推荐"，建议用公共函数读取
print(p._Person__gender)          # 私有属性被改名为 _Person__gender，据此可以强取（不推荐）


# ---------------------------------------------------------------------
# 三、修改属性值
# ---------------------------------------------------------------------
print("=" * 40)
print("三、修改属性值")
print("=" * 40)

p.name = "吴亦凡"                  # 公共属性可以直接修改
p._age = 35                       # 受保护属性也能改，但约定上不建议
print(p.name)                     # 输出：吴亦凡
print(p._age)                     # 输出：35

