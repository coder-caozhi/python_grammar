# =====================================================================
# 01. 创建类
# ---------------------------------------------------------------------
# 【类属性】  定义在类中、方法外，所有实例共享，用 类名.属性 访问
# 【实例属性】在 __init__ 中用 self.xxx 定义，每个实例各有一份
# 【修改类属性】只能通过 类名.属性 = 值
#             通过 实例.属性 = 值 时，只是给"该实例"加了一个同名属性，
#             类本身和其它实例都不受影响（详见第五节的对比）
# 【访问类属性】用"实例.属性"读取是可以的，只要该实例自己没有同名属性
#             读取顺序：先找实例自己的属性，找不到再向上找类属性
# =====================================================================


# ---------------------------------------------------------------------
# 一、定义类
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义类")
print("=" * 40)

class Person:
    """这是一个Person类"""

    home = "earth"                # 类属性，所有实例共享

    def __init__(self):
        self.age = 18             # 实例属性，每个实例各有一份


# ---------------------------------------------------------------------
# 二、获取类的成员（属性 / 文档 / 初始化函数）
# ---------------------------------------------------------------------
print("=" * 40)
print("二、获取类的成员")
print("=" * 40)

print(Person.home)                # 类属性，输出：earth
print(Person.__doc__)             # 类的说明文档，输出：这是一个Person类
print(Person.__init__)            # 初始化函数对象，输出：<function Person.__init__ at 0x...>


# ---------------------------------------------------------------------
# 三、修改类属性：只能通过"类名.属性名"
# ---------------------------------------------------------------------
print("=" * 40)
print("三、修改类属性")
print("=" * 40)

Person.home = "地球"              # 通过类名修改，所有实例都会受影响
print(Person.home)                # 输出：地球


# ---------------------------------------------------------------------
# 四、实例化并访问属性
# ---------------------------------------------------------------------
print("=" * 40)
print("四、实例化")
print("=" * 40)

p = Person()                      # 实例化，会自动调用 __init__
print(p.age)                      # 实例自己有的属性，输出：18
print(p.home)                     # p 自己没有 home → 向上找到类属性，输出：地球


# ---------------------------------------------------------------------
# 五、通过实例"修改类属性"的坑
# ---------------------------------------------------------------------
print("=" * 40)
print("五、通过实例修改类属性的坑")
print("=" * 40)

# 这一步并没有改到类属性，而是给实例 p 自己新增了一个 home 属性
# 注意：从这行开始，p 自己也有了 home，
#       第四节里"通过实例读到类属性"的情况对 p 就不再成立 ——
#       之后再读 p.home 拿到的都是这个"实例属性"
p.home = "火星"
print(p.home)                     # 输出：火星（p 自己的属性盖住了类属性）

p2 = Person()                     # 再创建一个新实例
print(p2.home)                    # 输出：地球（类属性其实并没有被改动）
