# =====================================================================
# 07. 继承 —— 单继承
# ---------------------------------------------------------------------
# 【语法】    class 子类(父类): ...
# 【继承】    子类自动拥有父类的属性和方法
# 【重写】    子类定义同名方法，会覆盖父类的方法
# 【super()】 在子类中调用父类的成员，最常用于补全父类的 __init__
# =====================================================================


# ---------------------------------------------------------------------
# 一、定义父类 Monkey
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义父类")
print("=" * 40)

class Monkey:

    def __init__(self, name):
        self.name = name

    def climb(self):
        print(f"{self.name} 在攀爬")

    def speak(self):
        print(f"{self.name} 在啊啊啊大叫")


# ---------------------------------------------------------------------
# 二、定义子类 Person：继承 Monkey
# ---------------------------------------------------------------------
print("=" * 40)
print("二、定义子类")
print("=" * 40)

class Person(Monkey):

    def __init__(self, name, age):
        super().__init__(name)    # 调用父类 __init__，把 name 交给父类处理
        self.age = age            # 子类自己扩展的属性

    def speak(self):              # 重写父类的 speak
        print(f"{self.name} 正在唱歌")

    def study(self):              # 子类独有的扩展方法
        print(f"{self.name} 正在思考未来")


# ---------------------------------------------------------------------
# 三、创建对象，调用三种不同来源的方法
# ---------------------------------------------------------------------
print("=" * 40)
print("三、调用方法")
print("=" * 40)

p = Person("王飞龙", 24)

p.climb()                         # 继承自父类，输出：王飞龙 在攀爬
p.speak()                         # 子类重写后的版本，输出：王飞龙 正在唱歌
p.study()                         # 子类独有，输出：王飞龙 正在思考未来
