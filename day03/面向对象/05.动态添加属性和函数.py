# =====================================================================
# 05. 动态添加属性和函数
# ---------------------------------------------------------------------
# 【原理】      Python 的类和对象都是"可变的"，可以在定义之外继续添加成员
# 【给类添加】  类名.属性 = 值 / 类名.方法名 = 函数 → 所有实例都能用
# 【给实例添加】实例.属性 = 值 → 只有该实例能用
# 【__slots__】 用元组限定实例"允许拥有的属性名"，可节省内存、防止乱加属性
# =====================================================================


# ---------------------------------------------------------------------
# 一、定义类，并用 __slots__ 限制实例能添加的属性名
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义类")
print("=" * 40)

class Person:
    # 实例只能拥有这三个属性名（名字不需要提前定义，存进去时会自动生成）
    __slots__ = ("name", "age", "sdy")


# ---------------------------------------------------------------------
# 二、在类外面准备"要动态添加的成员"
# ---------------------------------------------------------------------
print("=" * 40)
print("二、准备要动态添加的成员")
print("=" * 40)

@classmethod
def class_method(cls):
    """准备动态添加给 Person 类的类方法"""
    print("这是一个在类外面声明的要动态添加给类的一个类函数")


def study():
    """准备动态添加给实例的普通函数"""
    print("好好学习，天天向上")


# ---------------------------------------------------------------------
# 三、给"类"动态添加属性与方法（所有实例都生效）
# ---------------------------------------------------------------------
print("=" * 40)
print("三、给类动态添加成员")
print("=" * 40)

Person.home = "地球"              # 给类动态添加属性
print(Person.home)                # 输出：地球

Person.cls_method = class_method  # 给类动态添加类方法
Person.cls_method()               # 输出：这是一个在类外面声明的要动态添加给类的一个类函数


# ---------------------------------------------------------------------
# 四、给"实例"动态添加属性与方法（只对该实例生效）
# ---------------------------------------------------------------------
print("=" * 40)
print("四、给实例动态添加成员")
print("=" * 40)

p = Person()

p.age = 18                        # 属性名在 __slots__ 中，允许添加
print(p.age)                      # 输出：18

p.sdy = study                     # 函数名在 __slots__ 中，允许添加
p.sdy()                           # 输出：好好学习，天天向上
                                  # 注意：存进实例的普通函数不会自动绑定 self，按原样调用

p.name = "王飞龙"
print(p.name)                     # 输出：王飞龙


# ---------------------------------------------------------------------
# 五、__slots__ 的限制效果
# ---------------------------------------------------------------------
print("=" * 40)
print("五、__slots__ 的限制效果")
print("=" * 40)

