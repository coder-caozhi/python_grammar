# =====================================================================
# 09. 多态
# ---------------------------------------------------------------------
# 【概念】同一个函数（action）接收不同的对象，产生不同的行为
# 【前提】调用方只关心"对象有没有同名方法"（鸭子类型），不关心它是什么类
# 【注意】如果对象缺少被调用的方法，运行时会报 AttributeError（见文件末尾）
# =====================================================================

from random import randint        # 本文件未用到 randint，仅作演示保留


# ---------------------------------------------------------------------
# 一、定义一批"都有 eat 方法"的类
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义一批类")
print("=" * 40)

class Animal:
    def eat(self):
        print("大动物吃小动物")


class Dog:
    def eat(self):
        print("狗吃骨头")


class Cat:
    def eat(self):
        print("猫吃鱼")


class Pig:
    def eat(self):
        print("猪吃饲料")


class Bird:
    def fly(self):                # 注意：Bird 没有 eat，只有 fly
        print("我是一只小小鸟，我想要飞，取怎么也飞不高嗷嗷")


# ---------------------------------------------------------------------
# 二、定义一个"只依赖 eat 方法"的通用函数
# ---------------------------------------------------------------------
print("=" * 40)
print("二、定义通用函数")
print("=" * 40)

def action(animal):
    animal.eat()                  # 传入的对象只要有 eat() 就能正常工作


# ---------------------------------------------------------------------
# 三、传入不同对象，得到不同结果
# ---------------------------------------------------------------------
print("=" * 40)
print("三、多态演示")
print("=" * 40)

a = Animal()
d = Dog()
c = Cat()
p = Pig()
b = Bird()

action(a)                         # 输出：大动物吃小动物
action(d)                         # 输出：狗吃骨头
action(c)                         # 输出：猫吃鱼
action(p)                         # 输出：猪吃饲料

