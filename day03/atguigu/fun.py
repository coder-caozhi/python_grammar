# =====================================================================
# fun.py —— 包内的一个模块
# ---------------------------------------------------------------------
# 【__all__】 限制 from 模块 import * 时能导入哪些成员（只写字符串名）
# 【命名约定】变量名 / 函数名前加下划线表示"受保护"，加双下划线表示"私有"
#             （这只是约定，模块级别并不会真正阻止访问）
# 【__name__】直接运行本文件时为 "__main__"，被导入时为 "fun"
# =====================================================================

# 限制 from fun import * 时，只导入 num 这一个成员
__all__ = ["num"]


# ---------------------------------------------------------------------
# 一、模块中的变量
# ---------------------------------------------------------------------
num = 888                         # 公共变量
PI = 3.1415926                    # 常量（约定用全大写命名）
_my_str = "我是受保护的变量"       # 受保护的变量
__my_str2 = "我是一个私有变量"     # 私有的变量


# ---------------------------------------------------------------------
# 二、模块中的函数
# ---------------------------------------------------------------------
def fun():
    """公共函数"""
    print("我是一个公共的函数")


def _fun1():
    """受保护的函数"""
    print("我是一个受保护的函数")


def __fun2():
    """私有的函数"""
    print("我是一个私有的函数")


# ---------------------------------------------------------------------
# 三、__name__ 判断：只在"直接运行本文件"时执行，被导入时不执行
# ---------------------------------------------------------------------
# print(f"fun模块被导入后打印：{__name__}")

if __name__ == "__main__":
    print("直接执行的该文件")
