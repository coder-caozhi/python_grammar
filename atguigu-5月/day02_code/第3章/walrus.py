# ============================================================
# 场景一：在 if 中计算一个值，并在后面再次使用它
# ============================================================

print("\n========== 场景一：if 条件中的重复计算 ==========")

text = "Python"

# 写法 A：不使用海象运算符
print("\n--- 不使用海象运算符 ---")

if len(text) > 5:
    print(f"字符串长度是：{len(text)}")

# 问题：
# len(text) 在 if 条件中计算了一次，
# 在 print 中又计算了一次。
# 如果计算的是复杂的数据库查询、网络请求或复杂函数，就可能浪费资源。


# 写法 B：使用海象运算符
print("\n--- 使用海象运算符 ---")

if (n := len(text)) > 5:
    print(f"字符串长度是：{n}")


# 注意这一行：
# if (n := len(text)) > 5:
#
# 1. len(text) 被计算一次。
# 2. 计算结果同时赋值给 n。
# 3. 赋值完成后，整个 (n := len(text)) 表达式的值仍然是计算结果。
# 4. 因此可以直接拿它与 5 比较。
# 5. 进入 if 之后，n 也已经可以直接使用了。


# ============================================================
# 场景二：如果函数计算成本很高，差异就更明显
# ============================================================

print("\n========== 场景二：避免重复调用函数 ==========")


def calculate_price(price_text):
    print(f"    正在解析价格：{price_text}")
    return float(price_text)


# 写法 A：不使用海象运算符
print("\n--- 不使用海象运算符 ---")

if calculate_price("128.5") > 100:
    print(f"    最终价格：{calculate_price('128.5')}")

# 观察控制台：
# 正在解析价格：128.5
# 正在解析价格：128.5
#
# 同一个函数调用了两次。
# 如果函数内部包含复杂计算，就可能产生额外开销。


# 写法 B：使用海象运算符
print("\n--- 使用海象运算符 ---")

if (price := calculate_price("128.5")) > 100:
    print(f"    最终价格：{price}")

# 观察控制台：
# 正在解析价格：128.5
#
# 只调用了一次函数。
# 计算结果保存在 price 中，后面直接复用。


# ============================================================
# 场景三：while 循环中，先获取数据，再判断是否继续
# ============================================================

print("\n========== 场景三：while 循环 ==========")

# 假设我们正在逐行读取文件。
# 为了让代码可以直接运行，这里用迭代器模拟文件内容。


# 写法 A：不使用海象运算符
print("\n--- 不使用海象运算符 ---")

lines = iter(["第一行", "第二行", "第三行"])

while True:
    line = next(lines, None)  # 先获取一行

    if line is None:          # 再判断是否读完
        break

    print(line)

# 这里必须额外写一个 while True，
# 再手动获取数据、判断结束条件、使用 break。


# 写法 B：使用海象运算符
print("\n--- 使用海象运算符 ---")

lines = iter(["第一行", "第二行", "第三行"])

while (line := next(lines, None)) is not None:
    print(line)

# 现在：
# 1. next(lines, None) 获取下一行。
# 2. := 把获取到的内容赋值给 line。
# 3. is not None 判断是否读完。
# 4. 条件成立就进入循环，line 已经可以直接使用。
#
# 获取数据、赋值、判断是否继续，被整合进了一个条件表达式。


# ============================================================
# 场景四：列表推导式中，计算结果既要判断，又要保存
# ============================================================

print("\n========== 场景四：列表推导式 ==========")


def normalize_name(name):
    print(f"    正在处理：{name}")
    return name.strip().title()


raw_names = [" alice ", "bob", "charlotte", " tom "]


# 写法 A：不使用海象运算符
print("\n--- 不使用海象运算符 ---")

result_a = [
    normalize_name(name)
    for name in raw_names
    if len(normalize_name(name)) >= 5
]

print("结果：", result_a)

# 注意：
# 对于符合条件的元素，normalize_name(name) 会执行两次：
# 第一次：if 中计算长度。
# 第二次：生成列表元素。
#
# 例如 alice：
# 先处理一次，判断长度；
# 再处理一次，把结果放进列表。


# 写法 B：使用海象运算符
print("\n--- 使用海象运算符 ---")

result_b = [
    normalized
    for name in raw_names
    if len(normalized := normalize_name(name)) >= 5
]

print("结果：", result_b)

# 这里的顺序是：
# 1. normalize_name(name) 执行一次。
# 2. := 将结果保存到 normalized。
# 3. len(normalized) 判断是否满足条件。
# 4. 如果满足条件，直接将 normalized 放入列表。
#
# 同一份计算结果，既用于判断，又用于生成列表元素。


# ============================================================
# 场景五：有些地方，海象运算符确实没有必要
# ============================================================

print("\n========== 场景五：普通赋值就很好 ==========")

text = "Python"

# 写法 A：普通赋值
print("\n--- 普通赋值 ---")

n = len(text)

if n > 5:
    print(n)

# 写法 B：海象运算符
print("\n--- 海象运算符 ---")

if (n := len(text)) > 5:
    print(n)

# 两种写法都只计算一次 len(text)。
# 两种写法都很清晰。
#
# 如果你不介意多写一行，普通赋值完全没有问题。
# 海象运算符不是必须的，也不意味着代码一定更好。