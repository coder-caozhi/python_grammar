"""
    1、变量和常量的区别？
    变量代表在程序运行期间，可以被修改（被重新赋值）的，即变量的值会发生改变。
    常量代表在程序运行期间，不可以被修改（被重新赋值）的，即常量的值不会发生改变。
    
    2、在python中，常量只是约定，通过大写的命名方式来“约定”
    
    在C/C++中常量是要用const来特别定义的，修改就会报错的。
    在Java中常量是要用final来特别定义，修改就会报错的。
"""
MAX_VALUE = 100 #这就是一个常量
print("最大值：", MAX_VALUE)

