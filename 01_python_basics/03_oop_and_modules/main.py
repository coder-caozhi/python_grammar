# =====================================================================
# main.py —— 包 / 模块的导入演示
# ---------------------------------------------------------------------
# 【包】      含有 __init__.py 的文件夹；导入包时会自动执行 __init__.py
# 【导入方式】1. import 包.模块            → 完整导入，用"模块名.成员"访问
#             2. import 包.模块 as 别名     → 完整导入并起别名
#             3. from 包.模块 import 成员   → 精确导入，直接用成员名
# 【__name__】直接运行本文件时值为 "__main__"，被导入时值为模块名
# =====================================================================

import random                     # 标准库模块

# 导入 atguigu 包：__init__.py 中定义的成员（如 __author__）可以直接使用
import atguigu

# 完整导入 atguigu 包下的 fun 模块，并起别名为 fun
import atguigu.fun as fun

# 精确导入：只把 atguigu.fun2 中的 fun3 这个名字拿到当前文件
from atguigu.fun2 import fun3


# ---------------------------------------------------------------------
# 一、访问包 __init__.py 中定义的成员
# ---------------------------------------------------------------------
print("=" * 40)
print("一、访问包中定义的成员")
print("=" * 40)

print(atguigu.__author__)         # 输出：atguigu
print(atguigu.__version__)        # 输出：8.8.8


# ---------------------------------------------------------------------
# 二、通过"模块别名.成员"访问 fun 模块
# ---------------------------------------------------------------------
print("=" * 40)
print("二、访问模块成员")
print("=" * 40)

print(fun.num)                    # 公共变量，输出：888
print(fun.__my_str2)              # 私有变量（模块级不会改名，仍可访问），输出：我是一个私有变量
fun.fun()                         # 公共函数，输出：我是一个公共的函数
fun.__fun2()                      # 私有函数，输出：我是一个私有的函数


# ---------------------------------------------------------------------
# 三、调用精确导入的函数（直接用名字，不加模块名）
# ---------------------------------------------------------------------
print("=" * 40)
print("三、调用精确导入的函数")
print("=" * 40)

fun3()                            # 输出：测试精确导入


# ---------------------------------------------------------------------
# 四、使用标准库模块 random
# ---------------------------------------------------------------------
print("=" * 40)
print("四、使用标准库模块")
print("=" * 40)

print(random.randint(1, 10))      # 输出：1~10 之间的随机整数（每次运行结果不同）


# ---------------------------------------------------------------------
# 五、__name__ 属性：判断当前文件是"直接运行"还是"被导入"
# ---------------------------------------------------------------------
print("=" * 40)
print("五、__name__ 属性")
print("=" * 40)

print(__name__)                   # 直接运行本文件 → 输出：__main__
