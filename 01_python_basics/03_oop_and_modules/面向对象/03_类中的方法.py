# =====================================================================
# 03. 类中的方法
# ---------------------------------------------------------------------
# 【实例方法】def f(self)        第一个参数是"实例"，用 实例.方法() 调用
# 【类方法】  @classmethod       第一个参数是"类" cls，可以访问类属性
# 【静态方法】@staticmethod      没有 self / cls，通常作为工具函数
# 【魔法方法】__str__ 等，由 Python 在特定时机自动调用
# =====================================================================


# ---------------------------------------------------------------------
# 一、定义类
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义类")
print("=" * 40)

class Person:
    """这是一个Person类"""

    home = "earth"                # 类属性，所有实例共享

    def __init__(self, name, age, gender):
        self.name = name          # 公共属性，相当于 Java 中的 public
        self._age = age           # 受保护属性，相当于 Java 中的 protected
        self.__gender = gender    # 私有属性，相当于 Java 中的 private

    # ---------------------------- 实例方法 ----------------------------
    def eat(self):
        print(f"{self.name}正在吃东西")

    def drink(self):
        print(f"{self.name}正在喝饮料")

    # ---------------------------- 类方法 ------------------------------
    @classmethod
    def class_method(cls):
        """类方法：cls 代表类本身，所以可以访问类属性"""
        print(f"类的属性home的值是：{cls.home}")

    # --------------------------- 静态方法 -----------------------------
    @staticmethod
    def static_method():
        """静态方法：没有 self / cls，通常作为工具函数"""
        print("调用了静态函数")

    # --------------------------- 魔法方法 -----------------------------
    def __str__(self):
        """相当于 Java 中的 toString，print(实例) 时自动调用"""
        return f"Person(name={self.name}, age={self._age}, gender={self.__gender})"


# ---------------------------------------------------------------------
# 二、实例化并打印
# ---------------------------------------------------------------------
print("=" * 40)
print("二、实例化并打印")
print("=" * 40)

p = Person("吴亦凡", 35, "男")
print(p)                          # 触发 __str__，输出：Person(name=吴亦凡, age=35, gender=男)


# ---------------------------------------------------------------------
# 三、调用实例方法（通过实例调用）
# ---------------------------------------------------------------------
print("=" * 40)
print("三、调用实例方法")
print("=" * 40)

p.eat()                           # 输出：吴亦凡正在吃东西
p.drink()                         # 输出：吴亦凡正在喝饮料


# ---------------------------------------------------------------------
# 四、调用类方法（通过类调用，也可以用实例调用）
# ---------------------------------------------------------------------
print("=" * 40)
print("四、调用类方法")
print("=" * 40)

Person.class_method()             # 输出：类的属性home的值是：earth


# ---------------------------------------------------------------------
# 五、调用静态方法
# ---------------------------------------------------------------------
print("=" * 40)
print("五、调用静态方法")
print("=" * 40)

Person.static_method()            # 输出：调用了静态函数
