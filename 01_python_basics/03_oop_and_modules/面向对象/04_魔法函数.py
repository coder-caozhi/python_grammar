# =====================================================================
# 04. 魔法函数（双下划线方法）
# ---------------------------------------------------------------------
# 【特点】    名字形如 __xxx__，由 Python 在特定时机"自动"调用，不用手动调
# 【生命周期】__new__ 创建实例 → __init__ 初始化 → ... → __del__ 销毁
# 【__str__】 print(实例) / str(实例) 时触发，用来自定义打印格式
# 【__new__】 必须 return 一个实例，否则 __init__ 不会被调用
# =====================================================================


# ---------------------------------------------------------------------
# 一、定义类，观察各魔法函数的执行时机
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义类")
print("=" * 40)

class DemoClass:

    def __new__(cls, name):
        """1. 创建实例（最早被调用）"""
        print(f"调用 __new__ 创建 {cls.__name__} 实例")
        instance = super().__new__(cls)   # 借用父类的 __new__ 真正创建对象
        return instance

    def __init__(self, name):
        """2. 初始化实例（__new__ 返回实例后紧接着调用）"""
        print("调用 __init__ 初始化属性")
        self.name = name

    def __str__(self):
        """3. 执行 str(实例) 或 print(实例) 时被调用"""
        return f"DemoClass: name={self.name}"

    def __del__(self):
        """4. 实例销毁时被调用（引用计数归零时）"""
        print(f"调用 __del__ 销毁 {self.name} 实例")


# ---------------------------------------------------------------------
# 二、演示完整流程
# ---------------------------------------------------------------------
print("=" * 40)
print("二、魔法函数的执行顺序")
print("=" * 40)

obj = DemoClass("test")           # 触发 __new__ 和 __init__
print(obj)                        # 触发 __str__
del obj                           # 手动删除引用，触发 __del__
