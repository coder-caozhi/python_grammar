# =====================================================================
# 09. 循环
# ---------------------------------------------------------------------
# 【while】条件为真就一直循环（适合"次数不确定"的场景）
# 【for】遍历序列（列表、字符串、range 等）
# 【循环 + else】循环正常结束才执行 else；被 break 打断则不执行
# 【break / continue】break 跳出整个循环；continue 跳过本次进入下一次
# 【pass】占位语句，什么都不做
# =====================================================================


# ---------------------------------------------------------------------
# 一、while 循环（含 break 和 else）
# ---------------------------------------------------------------------
print("=" * 40)
print("一、while 循环")
print("=" * 40)

count = 0
while count < 10:                # 条件为 True 就一直循环
    if count == 6:
        break                    # 遇到 6 直接跳出整个循环
    print(count)                 # 输出：0 1 2 3 4 5
    count += 1
else:
    # else 只在循环"正常结束"时执行；被 break 打断就不会执行
    print("当循环被break了之后else将不会执行")
print("这是循环和else下面打印的内容")


# ---------------------------------------------------------------------
# 二、for 循环：遍历列表
# ---------------------------------------------------------------------
print("=" * 40)
print("二、for 遍历列表")
print("=" * 40)

my_list = ["罗志祥", "陶喆", "文章", "林丹", "吴秀波", "马蓉", "宋喆"]
for star in my_list:             # 依次把每个元素赋给 star
    print(f"生活糜烂的明星是：{star}")


# ---------------------------------------------------------------------
# 三、for 循环：遍历字符串
# ---------------------------------------------------------------------
print("=" * 40)
print("三、for 遍历字符串")
print("=" * 40)

my_str = "hello python"
for char in my_str:              # 逐个字符遍历
    print(char)


# ---------------------------------------------------------------------
# 四、range() 函数：生成整数序列（左闭右开）
# ---------------------------------------------------------------------
print("=" * 40)
print("四、range() 函数")
print("=" * 40)

# range(1, 9) 生成 1~8（包含 1，不包含 9）
my_list2 = list(range(1, 9))
print(my_list2)                  # 输出：[1, 2, 3, 4, 5, 6, 7, 8]

for num in my_list2:
    if num == 5:
        break                    # 到 5 就跳出，所以只打印 1~4
        # continue               # 若用 continue，会跳过 5 继续打印后面
    print(num)
else:
    print("for执行结束")


# ---------------------------------------------------------------------
# 五、嵌套循环：打印九九乘法表
# ---------------------------------------------------------------------
print("=" * 40)
print("五、嵌套循环")
print("=" * 40)

for i in range(1, 10):           # 外层控制"行"
    for j in range(1, i + 1):    # 内层控制"每行几列"
        print(f"{j}*{i}={i*j}", end=" ")   # end=" " 让结果不换行
    print("")                    # 每行结束换一次行


