# =====================================================================
# 01. 变量
# ---------------------------------------------------------------------
# 【命名规则】变量以数字、字母、下划线命名，不能以数字开头
# 【重要】    声明变量时不需要指定类型（Python 中一切皆对象）
# 【核心语法】变量名 = 值    → 把右边的值存起来，用左边的名字来引用它
# =====================================================================
"""
多行注释示例
在Python中一切皆对象
"""


# ---------------------------------------------------------------------
# 一、变量的基本使用：赋值 → 打印
# ---------------------------------------------------------------------
print("=" * 40)
print("一、变量的基本使用")
print("=" * 40)

# 语法：变量名 = 值
# 作用：把 1 这个值存进 my_var，之后用 my_var 就能取出 1
my_var = 1
print(my_var)                    # 输出：1


# ---------------------------------------------------------------------
# 二、id() 查看变量指向的"对象地址"
# ---------------------------------------------------------------------
# 语法：id(变量)
# 作用：打印该变量引用的对象在内存中的地址，用来观察"变量是否换了对象"
print(id(my_var))                # 输出：一串内存地址（每次运行可能不同）


# ---------------------------------------------------------------------
# 三、变量可以存放任意类型的数据
# ---------------------------------------------------------------------
print("=" * 40)
print("三、变量的类型")
print("=" * 40)

my_var2 = "hello"                # 字符串 str
print(my_var2)                   # 输出：hello

my_var3 = 6.66                   # 小数 float
print(my_var3)                   # 输出：6.66

my_var4 = False                  # 布尔 bool
print(my_var4)                   # 输出：False

my_var5 = True                   # 布尔 bool
print(my_var5)                   # 输出：True


# ---------------------------------------------------------------------
# 四、重新赋值：变量可以被覆盖，指向新的对象
# ---------------------------------------------------------------------
print("=" * 40)
print("四、重新赋值")
print("=" * 40)

my_var = 10                      # 原来的 1 被"抛弃"，my_var 现在指向 10
print(my_var)                    # 输出：10
print(id(my_var))                # 输出：新的内存地址（和上面 id(my_var) 不同）


# ---------------------------------------------------------------------
# 五、多变量赋值（两种写法）
# ---------------------------------------------------------------------
print("=" * 40)
print("五、多变量赋值")
print("=" * 40)

# 写法 1：给多个变量赋"同一个值"
a = b = c = 888
print(a)                         # 输出：888
print(b)                         # 输出：888
print(c)                         # 输出：888

# 写法 2：给多个变量"同时赋不同的值"（一一对应）
x, y, z = 11, 22, 33             # 注意：变量个数 = 值的个数
print(x)                         # 输出：11
print(y)                         # 输出：22
print(z)                         # 输出：33


# ---------------------------------------------------------------------
# 六、常量：约定俗成用"全大写字母"表示，值不应再修改
# ---------------------------------------------------------------------
print("=" * 40)
print("六、常量")
print("=" * 40)

PI = 3.141592653589793           # 常量用全大写命名（Python 不会强制，只是约定）
print(PI)                        # 输出：3.141592653589793
