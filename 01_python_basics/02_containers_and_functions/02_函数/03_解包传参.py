# =====================================================================
# 03. 解包传参
# ---------------------------------------------------------------------
# 【作用】  把 列表/元组/字典 一次性"拆开"传给函数
# 【*序列】 列表、元组 → 按位置拆成多个实参
# 【**字典】字典 → 按关键字拆成多个实参（键名必须等于形参名）
# =====================================================================


# 声明函数：形参 name、age
def get_info(name, age):
    print(f"您的姓名是：{name}，您今年{age}岁了")


# ---------------------------------------------------------------------
# 一、准备数据：列表、元组、字典
# ---------------------------------------------------------------------
print("=" * 40)
print("一、准备数据")
print("=" * 40)

my_list = ["关羽", 32]                   # 列表：元素顺序对应形参顺序
my_tuple = ("张飞", 31)                  # 元组：元素顺序对应形参顺序
my_dict = {"name": "诸葛亮", "age": 28}  # 字典：键名必须等于形参名

print(my_list, my_tuple, my_dict)


# ---------------------------------------------------------------------
# 二、* 解包：把序列按位置拆开传给函数
# ---------------------------------------------------------------------
print("=" * 40)
print("二、* 解包序列")
print("=" * 40)

get_info(*my_list)               # 等价于 get_info("关羽", 32)
get_info(*my_tuple)              # 等价于 get_info("张飞", 31)


# ---------------------------------------------------------------------
# 三、** 解包：把字典按关键字拆开传给函数
# ---------------------------------------------------------------------
print("=" * 40)
print("三、** 解包字典")
print("=" * 40)

get_info(**my_dict)              # 等价于 get_info(name="诸葛亮", age=28)

