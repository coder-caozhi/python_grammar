# =====================================================================
# 01. 声明函数
# ---------------------------------------------------------------------
# 【定义语法】def 函数名(参数列表): 函数体
# 【调用语法】函数名(实参列表)
# 【核心特点】函数也是对象，可以赋值给变量
# 【返回值】  return 返回结果；没有 return 时默认返回 None
# =====================================================================


# ---------------------------------------------------------------------
# 一、定义无参函数
# ---------------------------------------------------------------------
print("=" * 40)
print("一、定义无参函数")
print("=" * 40)

# 语法：def 函数名():
# 作用：把一段可复用的代码"打包"起来并起个名字，之后随时调用
def fun():
    """
    这是一个没有参数和返回值的函数
    :return: 没有返回值
    """
    print("hello function")


# ---------------------------------------------------------------------
# 二、调用函数
# ---------------------------------------------------------------------
print("=" * 40)
print("二、调用函数")
print("=" * 40)

# 语法：函数名()
# 作用：执行函数体内的代码；只定义不调用，函数体不会执行
fun()                            # 输出：hello function


# ---------------------------------------------------------------------
# 三、函数也是对象：可以赋值给变量
# ---------------------------------------------------------------------
print("=" * 40)
print("三、函数也是对象")
print("=" * 40)

# 注意：这里没写括号，是把"函数对象本身"赋给 my_var
my_var = fun
print(my_var)                    # 输出：<function fun at 0x...>，打印的是函数对象及其内存地址
my_var()                         # 输出：hello function（等价于 fun()）


# ---------------------------------------------------------------------
# 四、查看函数的文档说明
# ---------------------------------------------------------------------
print("=" * 40)
print("四、查看函数文档")
print("=" * 40)

# help(fun)：打印函数的帮助信息（包含文档字符串）
print(help(fun))

# 函数名.__doc__：只取出函数内部的文档字符串
print(fun.__doc__)


# ---------------------------------------------------------------------
# 五、没有返回值的函数，默认返回 None
# ---------------------------------------------------------------------
print("=" * 40)
print("五、函数的返回值")
print("=" * 40)

# 函数内部没有 return，Python 会自动返回 None
print(fun())                     # 输出：hello function，然后打印 None


# ---------------------------------------------------------------------
# 六、定义有参数、有返回值的函数
# ---------------------------------------------------------------------
print("=" * 40)
print("六、有参有返回值的函数")
print("=" * 40)

# 语法：def 函数名(形参1, 形参2): ... return 结果
def add(a, b):
    """
    这是一个求和的函数
    :param a: 第一个参数
    :param b: 第二个参数
    :return: 返回a和b的和
    """
    return a + b

# 调用：把 10、2 传给形参 a、b，用 result 接收返回值
result = add(10, 2)
print(result)                    # 输出：12


# ---------------------------------------------------------------------
# 七、函数注解：给参数和返回值加"类型/说明"提示
# ---------------------------------------------------------------------
print("=" * 40)
print("七、函数注解")
print("=" * 40)

# 语法：def 函数名(参数: 注解) -> 返回值注解:
# 注意：注解只是"提示"，Python 不会强制校验
def my_fun(name: "这是姓名", age: "范围是0-116", gender: int) -> "返回值是字典":
    return {"姓名": name, "年龄": age, "性别": gender}

# 函数名.__annotations__：取出所有注解，存成一个字典
print(my_fun.__annotations__)
print(my_fun("蔡徐坤", 27, 1))
