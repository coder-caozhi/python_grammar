# =====================================================================
# 05. 作用域
# ---------------------------------------------------------------------
# 【局部作用域】函数内部定义的变量（Local）
# 【嵌套作用域】外层函数里的变量（Enclosing）
# 【全局作用域】模块（文件）最外层定义的变量（Global）
# 【内建作用域】Python 内置的名字（Built-in，如 print、len）
# 【查找顺序】  Local → Enclosing → Global → Built-in（简称 LEGB）
# =====================================================================

# 全局作用域：定义在函数外部
a = 10


# ---------------------------------------------------------------------
# 一、嵌套函数：函数内部再定义函数
# ---------------------------------------------------------------------
def parent_fun():
    # 嵌套作用域：定义在外层函数内部
    a = 100

    def child_fun():
        # 局部作用域：定义在最内层函数内部
        a = 1000
        print(a)                 # 就近原则：找到局部的 a → 输出 1000

    # 调用子函数
    child_fun()


# ---------------------------------------------------------------------
# 二、调用 parent_fun，观察 a 的取值
# ---------------------------------------------------------------------
print("=" * 40)
print("二、作用域的查找顺序")
print("=" * 40)

"""
    打印 a 时的查找顺序：
        先找 局部作用域(Local) → 再找 嵌套作用域(Enclosing)
        → 再找 全局作用域(Global) → 最后找 内建作用域(Built-in)
        都找不到才会报错
"""
parent_fun()                     # 输出：1000



