# =====================================================================
# 02. 元组
# ---------------------------------------------------------------------
# 【特点】    有序、不可变、可重复、值类型不限
# 【创建方式】1. 使用小括号()
#             （注意：只有一个元素时，元素后面必须加逗号）
#             2. 使用 tuple() 函数
# 【获取元素】1. 索引下标   2. 遍历   3. enumerate
# 【注意】    元素一旦创建就不能修改，所以只有"查"相关的方法
# =====================================================================


# ---------------------------------------------------------------------
# 一、使用 () 创建元组
# ---------------------------------------------------------------------
print("=" * 40)
print("一、使用 () 创建元组")
print("=" * 40)

my_tuple = (1, 2, 3)
print(my_tuple)                   # 输出：(1, 2, 3)
print(type(my_tuple))             # 输出：<class 'tuple'>


# ---------------------------------------------------------------------
# 二、使用 tuple() 函数创建元组
# ---------------------------------------------------------------------
print("=" * 40)
print("二、使用 tuple() 函数创建元组")
print("=" * 40)

my_tuple2 = tuple("hello")        # 把可迭代对象的每个元素依次装入元组
print(my_tuple2)                  # 输出：('h', 'e', 'l', 'l', 'o')
print(type(my_tuple2))            # 输出：<class 'tuple'>


# ---------------------------------------------------------------------
# 三、单元素元组的坑：元素后面必须加逗号
# ---------------------------------------------------------------------
print("=" * 40)
print("三、单元素元组")
print("=" * 40)

my_tuple3 = (8,)                  # 注意：(8,) 才是元组；(8) 只是数字 8
print(my_tuple3)                  # 输出：(8,)
print(type(my_tuple3))            # 输出：<class 'tuple'>


# ---------------------------------------------------------------------
# 四、获取元素：索引 / 遍历 / enumerate
# ---------------------------------------------------------------------
print("=" * 40)
print("四、获取元素")
print("=" * 40)

print(my_tuple[0])                # 索引下标，输出：1

for a in my_tuple:                # 遍历：依次取出每个元素
    print(a)

for i, x in enumerate(my_tuple):  # enumerate：同时拿到索引和元素
    print(f"元素的索引是：{i}，元素值是：{x}")


# ---------------------------------------------------------------------
# 五、常用方法与运算
# ---------------------------------------------------------------------
print("=" * 40)
print("五、常用方法与运算")
print("=" * 40)

print(my_tuple.index(3))          # 获取元素的索引，输出：2
print(my_tuple2.count("h"))       # 统计元素出现次数，输出：1
print(len(my_tuple))              # 获取长度，输出：3
print(my_tuple + my_tuple2)       # 相加：拼接成一个新元组
print(my_tuple * 3)               # 相乘：元素重复 3 次
print(sum(my_tuple))              # 求和，输出：6
