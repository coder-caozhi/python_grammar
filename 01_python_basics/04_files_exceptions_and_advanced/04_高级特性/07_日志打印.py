# =====================================================================
# 07. 日志打印（logging）
# ---------------------------------------------------------------------
# 【为什么不用 print】print 没法分级、没法输出到文件、没法带时间/行号，
#                     正式项目里都用 logging
# 【五个级别】由低到高 DEBUG < INFO < WARNING < ERROR < CRITICAL
#             设置 level=INFO 后，DEBUG 级别的日志就不会输出了
# 【四件套】
#     level    → 最低输出级别（低于它的直接丢弃）
#     format   → 日志格式模板
#     handlers → 输出目的地（控制台 / 文件，可以同时配置多个）
#     logger   → 真正用来打日志的对象
# =====================================================================

import logging


# ---------------------------------------------------------------------
# 一、日志的基本配置
# ---------------------------------------------------------------------
print("=" * 40)
print("一、基本配置")
print("=" * 40)

logging.basicConfig(
    # 设置最低输出级别为 DEBUG（也就是所有级别都会输出）
    level=logging.DEBUG,

    # 格式模板，各占位符含义：
    #   %(asctime)s    时间
    #   %(name)s       日志器名称（这里是 __main__）
    #   %(levelname)s  级别名（INFO / DEBUG / ERROR）
    #   %(filename)s   所在文件名
    #   %(lineno)d     所在行号
    #   %(message)s    你写的日志内容
    format='%(asctime)s - %(name)s - %(levelname)s - %(filename)s:%(lineno)d - %(message)s',

    # handlers：同时输出到"控制台"和"文件"
    handlers=[
        logging.StreamHandler(),                              # 控制台
        logging.FileHandler('app.log', encoding='utf-8')      # 追加写入 app.log
    ]
)

# 注意：basicConfig 只生效一次，重复调用不会覆盖已有配置


# ---------------------------------------------------------------------
# 二、获取 logger 并打日志
# ---------------------------------------------------------------------
print("=" * 40)
print("二、打印日志")
print("=" * 40)

# __name__ 就是当前模块名：直接运行本文件时是 "__main__"，被导入时是模块名
logger = logging.getLogger(__name__)

logger.info("普通日志")               # INFO 级别
logger.debug("Debug级别的日志")       # DEBUG 级别
logger.error("错误日志")              # ERROR 级别

# 控制台输出（行号就是上面三行 logger 调用所在的实际行号）：
# 2026-10-07 00:34:43,385 - __main__ - INFO - 07.日志打印.py:58 - 普通日志
# 2026-10-07 00:34:43,386 - __main__ - DEBUG - 07.日志打印.py:59 - Debug级别的日志
# 2026-10-07 00:34:43,386 - __main__ - ERROR - 07.日志打印.py:60 - 错误日志
#
# 同时这三行也写进了同目录下的 app.log（打开文件可以看到）


# ---------------------------------------------------------------------
# 三、级别对照表
# ---------------------------------------------------------------------
#   级别        数值    什么时候用
#   --------------------------------------------------------
#   DEBUG       10     调试细节，比如循环里打印变量
#   INFO        20     正常流程的关键节点（启动、请求完成）
#   WARNING     30     有问题但不影响运行（即将废弃、磁盘将满）
#   ERROR       40     出错了，某功能不可用
#   CRITICAL    50     严重到程序可能崩掉
#
#   若把 level 改成 logging.WARNING：
#       上面三条里只有 error 那条会输出，info 和 debug 会被过滤掉


# ---------------------------------------------------------------------
# 四、几个实用细节
# ---------------------------------------------------------------------
#   1. 生产环境常用 RotatingFileHandler 做日志切割：
#      logging.handlers.RotatingFileHandler("app.log", maxBytes=5*1024*1024,
#                                            backupCount=3)
#      → 单个文件超过 5MB 就自动轮转，最多保留 3 个历史文件
#
#   2. 想用 f-string 风格又保留惰性求值，可以用：
#      logger.info("用户 %s 登录成功", username)
#      比 f"..." 更好：级别被过滤时不会白做字符串拼接
#
#   3. 写日志时不要用 %(message)s 之外的占位符去拼敏感信息
#      （密码、token 不应该出现在日志里）
