# =====================================================================
# 01. 异常处理 —— 基本语法
# ---------------------------------------------------------------------
# 【四个关键字的分工】
#     try       → 放"可能会出错"的代码
#     except    → 出错时执行（可以写多个，从上往下匹配，第一个匹配的生效）
#     else      → 只有"没出错"时才执行
#     finally   → 不管有没有出错都执行（常用于释放资源：关文件、关连接）
# 【执行顺序】try 出错 → except ；try 没出错 → else ；finally 永远执行
# 【常见异常】ZeroDivisionError / NameError / TypeError / KeyError / IndexError
# =====================================================================


# ---------------------------------------------------------------------
# 一、只处理一种异常
# ---------------------------------------------------------------------
print("=" * 40)
print("一、只处理一种异常")
print("=" * 40)

try:
    # 把下面这行的注释打开，就会触发除 0 异常
    # num = 10 / 0
    print("执行try中的代码")
except ZeroDivisionError as e:
    # as e：把异常对象接到 e 上，才能拿到异常信息
    print(f"出现了异常，异常信息是：{e}")
else:
    print("不出现异常时才会执行的代码")
finally:
    print("不管程序是否出现异常都要执行的代码")

# 输出（因为没触发异常）：
#   执行try中的代码
#   不出现异常时才会执行的代码
#   不管程序是否出现异常都要执行的代码


# ---------------------------------------------------------------------
# 二、同时处理多种异常
# ---------------------------------------------------------------------
print("=" * 40)
print("二、同时处理多种异常")
print("=" * 40)

try:
    # 依次把注释打开，可以看到会被不同的 except 捕获
    # num = 10 / 0                  # → ZeroDivisionError
    # print(num)                    # → NameError（num 未定义）
    str = 5 + "hello"               # → TypeError（int 和 str 不能相加）
    print(str)
    print("执行try中的代码")
except (ZeroDivisionError, NameError) as e:
    # 多个异常写在一个括号里，表示它们共用同一段处理逻辑
    print(f"出现了异常，异常信息是：{e}")
except TypeError as e:
    # 更具体的异常要写在前面，否则会被后面的 Exception 提前截胡
    print(f"出现了类型异常，异常信息是：{e}")
except Exception as e:
    # Exception 是所有普通异常的父类，放在最后当"兜底"
    print(f"出现了其他异常，异常信息是：{e}")
else:
    print("不出现异常时才会执行的代码")
finally:
    print("不管程序是否出现异常都要执行的代码")

# 输出（触发的是 TypeError）：
#   出现了类型异常，异常信息是：unsupported operand type(s) for +: 'int' and 'str'
#   不管程序是否出现异常都要执行的代码


# ---------------------------------------------------------------------
# 三、几个必须记住的规则
# ---------------------------------------------------------------------
#   1. except 从上往下匹配，命中第一个就跳出，后面的不再看
#      → 所以"具体异常"要写在"宽泛异常"前面
#   2. finally 即使 try 里有 return，也会在 return 之前执行
#   3. 不要把代码写成 "什么都捕获"
#         except Exception: pass     ← ❌ 会把真正的 bug 也吞掉，极难排查
#      至少要 print / log 出异常信息
