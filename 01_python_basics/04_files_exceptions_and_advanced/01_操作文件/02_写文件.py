# =====================================================================
# 02. 写文件
# ---------------------------------------------------------------------
# 【文件不存在时】会自动创建（前提是所在目录已存在）
# 【两种模式】
#     "w" → 覆盖写：先清空文件，再从开头写。连着调用两次 = 只剩最后一次
#     "a" → 追加写：在文件末尾接着写，原有内容保留
# 【写换行】write 不会自动换行，要自己写 "\n"
# 【注意】"w" 非常危险 —— 一旦执行，原内容立刻没了，无法撤销
# =====================================================================


# ---------------------------------------------------------------------
# 一、覆盖写
# ---------------------------------------------------------------------
print("=" * 40)
print("一、覆盖写")
print("=" * 40)


def write_file(file_path, encoding):
    with open(file_path, mode="w", encoding=encoding) as f:
        # 不写 "\n" 就会全部挤在同一行
        f.write("今天天气好晴朗")
        f.write("处处好风光")                # 和上一行拼在一起
        f.write("\n")                       # 手动换行

        # 换行写：在字符串末尾加 \n
        f.write("蝴蝶儿忙，蜜蜂也忙\n")
        f.write("小鸟儿忙着，白云也忙\n")


# ---------------------------------------------------------------------
# 二、追加写
# ---------------------------------------------------------------------
print("=" * 40)
print("二、追加写")
print("=" * 40)


def append_file(file_path, encoding):
    with open(file_path, mode="a", encoding=encoding) as f:
        # "a" 模式在文件末尾接着写，原有内容不会丢
        f.write("\n")
        f.write("爱到心破碎，也别去怪谁\n")
        f.write("只因为相遇太美\n")


# ---------------------------------------------------------------------
# 三、调用
# ---------------------------------------------------------------------
print("=" * 40)
print("三、调用")
print("=" * 40)

# 覆盖写：会把 test2.txt 清空后重写（第一次实验时用）
# write_file("test2.txt", "utf-8")

# 追加写：在文件末尾接着写
append_file("test2.txt", "utf-8")

print("写入完成，test2.txt 当前内容如下：")
with open("test2.txt", mode="r", encoding="utf-8") as f:
    print(f.read())

# 注意：每运行一次这个文件，"爱到心破碎..." 就会再追加一遍，
#       所以多次运行后文件里会出现重复内容 —— 这是 "a" 模式的正常表现


# ---------------------------------------------------------------------
# 四、对比小结
# ---------------------------------------------------------------------
#        模式    文件已存在时        文件不存在时
#   -------------------------------------------------
#    "w"    清空原内容再写      新建
#    "a"    末尾接着写          新建
#    "r"    只读（写会报错）    报 FileNotFoundError
#    "x"    报错                新建（用于"不想覆盖"的场景）
