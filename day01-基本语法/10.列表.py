# =====================================================================
# 10. 列表 list
# ---------------------------------------------------------------------
# 【创建】[]  或  list()
# 【特点】有序、可变、可重复、元素类型不限
# 【访问】下标（从 0 开始）、遍历
# 【常用方法】append / extend / insert / pop / remove / index / sort / reverse
# =====================================================================


# ---------------------------------------------------------------------
# 一、创建列表
# ---------------------------------------------------------------------
print("=" * 40)
print("一、创建列表")
print("=" * 40)

# 方式 1：直接使用 []，元素类型可混搭，还能嵌套
my_list = [1, "hello", True, 8.88, ["hello", "蔡徐坤"]]
print(my_list)

# 方式 2：使用 list()，把其它序列转成列表
my_list2 = list(range(1, 10, 2))  # range(起始, 结束, 步长) → 1 3 5 7 9
print(my_list2)


# ---------------------------------------------------------------------
# 二、访问元素：用下标（从 0 开始）
# ---------------------------------------------------------------------
print("=" * 40)
print("二、访问元素")
print("=" * 40)

# 二维列表：先取外层下标，再取内层下标
print(my_list[4][1])             # 输出：蔡徐坤


# ---------------------------------------------------------------------
# 三、修改元素
# ---------------------------------------------------------------------
print("=" * 40)
print("三、修改元素")
print("=" * 40)

print(id(my_list2))              # 修改前，先记下列表对象地址
my_list2[1] = 5                  # 把下标 1 的元素改成 5
print(my_list2)
print(id(my_list2))              # 修改后地址不变 → 列表是"可变"的


# ---------------------------------------------------------------------
# 四、常用方法
# ---------------------------------------------------------------------
print("=" * 40)
print("四、常用方法")
print("=" * 40)

# append(x)：在末尾追加"一个"元素
my_list2.append(5)
print(my_list2)

# extend(列表)：在末尾追加"多个"元素
my_list2.extend([1, 2, 3])
print(my_list2)

# insert(下标, 元素)：在指定位置插入元素
my_list2.insert(1, "hello")
print(my_list2)

# pop(下标)：取出并删除指定位置的元素（不写下标则删最后一个，即"出栈"）
my_list2.pop(1)
print(my_list2)

# remove(值)：删除第一个出现的指定值
my_list2.remove(5)
print(my_list2)

# index(值)：查找元素第一次出现的下标
print(my_list2.index(7))


# ---------------------------------------------------------------------
# 五、排序与反转
# ---------------------------------------------------------------------
print("=" * 40)
print("五、排序与反转")
print("=" * 40)

# sort()：升序排序；sort(reverse=True)：降序排序（都是原地修改）
# my_list2.sort()
# my_list2.sort(reverse=True)

print(f"反转前的列表是：{my_list2}")
my_list2.reverse()               # reverse()：把列表前后反转
print(f"反转后的列表是：{my_list2}")
