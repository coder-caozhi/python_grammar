# =====================================================================
# 05. 输入输出
# ---------------------------------------------------------------------
# 【输入】input(提示语) → 从控制台读取内容，返回值"永远是字符串"
# 【输出】print(内容)   → 打印内容，默认会自动换行
# 【格式化输出】%占位符 / format() / f-string（推荐 f-string）
# =====================================================================


# ---------------------------------------------------------------------
# 一、input()：接收用户输入
# ---------------------------------------------------------------------
print("=" * 40)
print("一、input() 输入")
print("=" * 40)

# 注意：input 返回的永远是字符串 str，需要数字时要自己转换
# name = input("请输入您的姓名：")
# print(type(name))              # <class 'str'>
# age = input("请输入您的年龄：")
# print(type(age))               # <class 'str'>


# ---------------------------------------------------------------------
# 二、print()：输出内容
# ---------------------------------------------------------------------
print("=" * 40)
print("二、print() 输出")
print("=" * 40)

name = "吴签"
age = 28
salary = 3000.567

print(name)                      # 输出：吴签
print(age)                       # 输出：28
print(salary)                    # 输出：3000.567（print 默认自动换行）

# 巧用"字符串 × 数字"，快速打印重复符号当分隔线
print("*" * 30)                  # 输出 30 个 *
print("=" * 60)                  # 输出 60 个 =


# ---------------------------------------------------------------------
# 三、格式化输出（三种写法，推荐第 3 种）
# ---------------------------------------------------------------------
print("=" * 40)
print("三、格式化输出")
print("=" * 40)

# 写法 1：% 占位符   %s=字符串  %d=整数  %.2f=保留 2 位小数
print("我叫%s，我今年%d岁，我的工资是每月%.2f元" % (name, age, salary))

# 写法 2：format()，用 {} 占位
print("我叫{}，我今年{}岁，我的工资是每月{}元".format(name, age, salary))

# 写法 3：f-string（最直观：字符串前加 f，变量直接写在 {} 里）
print(f"我叫{name},我今年{age}岁，我的工资是每月{salary}元")
# f-string 里也能直接格式化，例如保留两位小数
print(f"工资保留两位小数：{salary:.2f}元")


# ---------------------------------------------------------------------
# 四、print() 的 end 参数：控制结尾字符
# ---------------------------------------------------------------------
print("=" * 40)
print("四、print() 的 end 参数")
print("=" * 40)

# 默认 end="\n" 会换行；改成 end='' 就不换行
print(f"我叫{name},", end='')
print(f"我的年龄是{age}岁")