# =====================================================================
# 07. 成员运算符和身份运算符
# ---------------------------------------------------------------------
# 【成员运算符】in / not in  → 判断"某元素在不在"字符串或容器里
# 【身份运算符】is / is not  → 判断两个变量是否指向"同一个对象"
# 【关键区别】== 比的是"值"；  is 比的是"是不是同一个对象"
# =====================================================================


# ---------------------------------------------------------------------
# 一、成员运算符 in / not in
# ---------------------------------------------------------------------
print("=" * 40)
print("一、成员运算符")
print("=" * 40)

# 判断字符是否在字符串里
my_str = "hello"
print("e" in my_str)             # 输出：True   → e 在 hello 里
print("a" not in my_str)         # 输出：True   → a 不在 hello 里

# 判断元素是否在列表里
my_list = [1, "a", 6.66, True]
print(1 in my_list)              # 输出：True
print("a" not in my_list)        # 输出：False  → a 在列表里，所以 not in 为 False


# ---------------------------------------------------------------------
# 二、身份运算符 is / is not
# ---------------------------------------------------------------------
# 核心一句话：双等号 == 比较的是"内容（值）"，is 比较的是"地址（是不是同一个对象）"
# 类比：== 类似 Java 的 equals（比内容）；is 类似 Java 的 ==（比地址）
# ---------------------------------------------------------------------
print("=" * 40)
print("二、身份运算符")
print("=" * 40)

# 小整数（-5 ~ 256）Python 会缓存复用，所以两个 10 是"同一个对象"
num = 10
num2 = 10
print(num == num2)               # 输出：True   → == 比内容（值相等）
print(id(num))                   # 输出：对象地址
print(num is num2)               # 输出：True   → is 比地址（连对象都同一个，被缓存）
print(id(num2))                  # 输出：和上面相同

# 注意：下面的 1000 "是同一个对象" 不是小整数缓存（1000 超出了 -5 ~ 256 范围），
# 而是【编译期常量去重】：同一个模块编译时，相同字面量在常量表 co_consts 里只存一份，
# 所以两处 1000 引用的是同一个常量对象。这是 CPython 的实现细节，不是语言保证！
num3 = 1000
num4 = 1000
print(num3 == num4)              # 输出：True   → 值相等
print(id(num3))
print(num3 is num4)              # 输出：True   → 指向同一对象（编译期字面量复用）
print(id(num4))

print(num3 is not num4)          # 输出：False  → 因为它们是同一个对象

# 对比：如果 1000 是"运行时算出来"的，就不再是同一个对象，is 会返回 False
a = int("1000")
b = int("1000")
print(a == b)                    # 输出：True   → 值仍然相等
print(a is b)                    # 输出：False  → 运行期各自新建对象，地址不同
print(id(a))
print(id(b))

# 结论：比较"值"永远用 ==；is 只用于 None / True / False 这类单例判断
