# =====================================================================
# 08. 流程控制
# ---------------------------------------------------------------------
# 【if 单分支】条件成立才执行缩进里的代码
# 【if-elif-else 多分支】从上往下依次判断，命中一个就结束
# 【嵌套 if】if 里面再写 if
# 【match-case】按值匹配不同分支（Python 3.10+）
# =====================================================================


# ---------------------------------------------------------------------
# 一、if 单分支
# ---------------------------------------------------------------------
print("=" * 40)
print("一、if 单分支")
print("=" * 40)

age = 1
if age > 18:                     # 条件为 True 才执行下面缩进的代码
    print("你是一个成年人")


# ---------------------------------------------------------------------
# 二、if-elif-else 多分支（含嵌套）
# ---------------------------------------------------------------------
print("=" * 40)
print("二、if-elif-else 多分支")
print("=" * 40)

if 0 <= age <= 3:                # 支持连续比较写法
    if age <= 1:                 # 嵌套 if：在 if 内部再判断
        print("哺乳期")
    elif age <= 2:
        print("哺乳期已结束")
    else:
        print("该上幼儿园了")
elif 3 < age < 12:
    print("儿童")
elif 13 < age < 17:
    print("青少年")
elif 17 < age < 44:
    print("青年")
elif 44 < age < 59:
    print("中年")
elif 60 < age < 116:
    print("老年")
else:
    print("您已成仙")


# ---------------------------------------------------------------------
# 三、match-case：按值匹配分支
# ---------------------------------------------------------------------
print("=" * 40)
print("三、match-case")
print("=" * 40)

status = 600
match status:                    # 用 status 的值逐个匹配下面的 case
    case 200:
        print("请求成功")
    case 302:
        print("重定向")
    case 403:
        print("无权访问")
    case 404:
        print("您请求的资源到火星了")
    case 405:
        print("请求方式不允许")
    case 500:
        print("服务器内部错误")
    case _:                      # _ 表示"其它所有情况"（相当于 else）
        print("未知的状态码")
