# ---------------------------------------------------------------------
# 一、用 type() 查看变量的类型
# ---------------------------------------------------------------------
print("=" * 40)
print("一、用 type() 查看类型")
print("=" * 40)

num = 1
print(type(num))                 # 输出：<class 'int'>    → 整数

num1 = 8.88
print(type(num1))                # 输出：<class 'float'>  → 浮点数

num2 = True
print(type(num2))                # 输出：<class 'bool'>   → 布尔


# ---------------------------------------------------------------------
# 二、数值类型的小细节
# ---------------------------------------------------------------------
print("=" * 40)
print("二、数值类型的小细节")
print("=" * 40)

# 语法：用下划线 _ 分隔长数字，方便阅读（不影响数值大小）
num3 = 1_000_000_000_000
print(type(num3))                # 输出：<class 'int'>
print(num3)                      # 输出：1000000000000

# 布尔 bool 是整数 int 的"子类型"（True=1，False=0）
# 语法：int(布尔值)  → 显式（强制）类型转换，把 bool 转成 int
num4 = False
print(int(num4))                 # 输出：0  → False 强转成 0

num5 = True
print(int(num5))                 # 输出：1  → True 强转成 1

print(isinstance(num4, int))     # 输出：True  → 布尔本质上也是整数

# 反过来也可以：int(0) / int(1) 用 bool() 转回布尔
print(bool(0))                   # 输出：False  → 0 转成 False
print(bool(1))                   # 输出：True   → 非 0 转成 True


# ---------------------------------------------------------------------
# 三、可变类型 vs 不可变类型
# ---------------------------------------------------------------------
# 不可变类型：数值、字符串、元组  → 改值会"换一个新对象"（id 会变）
# 可变类型：  列表、集合、字典    → 改值还是"同一个对象"（id 不变）
# ---------------------------------------------------------------------
print("=" * 40)
print("三、可变类型 vs 不可变类型")
print("=" * 40)

# 字符串是不可变的：重新赋值时，其实是换了一个新对象
my_str = 'hello'
print(my_str)                    # 输出：hello
print(id(my_str))                # 输出：字符串对象地址 A
my_str = "python"                # 相当于换了一个新对象
print(my_str)                    # 输出：python
print(id(my_str))                # 输出：地址 B（和 A 不同）

# 列表是可变的：修改里面的元素，对象本身还是同一个
my_list = [1, 2, 3, 4]
print(my_list)                   # 输出：[1, 2, 3, 4]
print(id(my_list))               # 输出：列表对象地址 C
c = id(my_list)
my_list[0] = 100                 # 修改第 1 个元素
print(my_list)                   # 输出：[100, 2, 3, 4]
print(id(my_list))               # 输出：地址仍是 C（对象没变）
print(id(my_list) == c)          # 输出：一定是True


