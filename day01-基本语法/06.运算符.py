# =====================================================================
# 06. 运算符
# ---------------------------------------------------------------------
# 【算术】+ - * / // % **
# 【赋值】= += -= *= /= //= **=
# 【海象】:=              → 边判断边赋值
# 【比较】> < >= <= == != → 结果是 True / False
# 【逻辑】and or not      → 有"短路"特性
# =====================================================================


# ---------------------------------------------------------------------
# 一、算术运算符
# ---------------------------------------------------------------------
print("=" * 40)
print("一、算术运算符")
print("=" * 40)

a = 10
b = 3
result1 = a / b                  # 除法：结果一定是浮点数
result2 = a // b                 # 整除：只要商（向下取整）
result3 = a % b                  # 取模：只要余数
result4 = a ** b                 # 幂运算：a 的 b 次方
print(result1)                   # 输出：3.3333333333333335
print(result2)                   # 输出：3
print(result3)                   # 输出：1
print(result4)                   # 输出：1000


# ---------------------------------------------------------------------
# 二、赋值运算符（复合赋值）
# ---------------------------------------------------------------------
print("=" * 40)
print("二、赋值运算符")
print("=" * 40)

a /= 4                           # 等价于 a = a / 4
print(a)                         # 输出：2.5
a //= 4                          # 等价于 a = a // 4
print(a)                         # 输出：0.0
b **= 3                          # 等价于 b = b ** 3
print(b)                         # 输出：27


# ---------------------------------------------------------------------
# 三、海象运算符 :=（判断 + 赋值一步到位）
# ---------------------------------------------------------------------
print("=" * 40)
print("三、海象运算符 :=")
print("=" * 40)

age = 20
# 先算 age >= 18 得到 True，赋给 my_age，再判断
if my_age := age >= 18:
    print(f"是否是成年人：{my_age}")   # 输出：是否是成年人：True

text = "hello"
# 先算 len(text) 得到 5 并赋给 length，再判断 5 > 3
if (length := len(text)) > 3:
    print(f"长度是 {length}")          # 输出：长度是 5


# ---------------------------------------------------------------------
# 四、比较运算符
# ---------------------------------------------------------------------
print("=" * 40)
print("四、比较运算符")
print("=" * 40)

print(a > b)                     # 比较大小，结果是 True/False
print(a <= b)
print(a == b)                    # == 判断"值"是否相等


# ---------------------------------------------------------------------
# 五、逻辑运算符 and / or / not（重点：短路）
# ---------------------------------------------------------------------
print("=" * 40)
print("五、逻辑运算符")
print("=" * 40)

print(age > 18 and len(text) > 3)   # and：两边都 True 才 True
print(age <= 18 or len(text) > 3)   # or：有一个 True 就 True
print(not age > 18)                 # not：取反

# 短路特性：and 左边为 False、or 左边为 True 时，右边"不再计算"
# 下面两行都不会报除零错误，正是因为有短路
print(age < 18 and 10 / 0)       # 输出：False（左边已 False，右边跳过）
print(age >= 18 or 10 / 0)       # 输出：True （左边已 True，右边跳过）
