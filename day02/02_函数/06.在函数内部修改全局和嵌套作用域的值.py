# =====================================================================
# 06. 在函数内部修改全局和嵌套作用域的值
# ---------------------------------------------------------------------
# 【不可变类型】int/str/tuple 等，函数内直接赋值只是新建局部变量
#              → 想改全局必须用 global 声明
# 【可变类型】  list/dict/set 等，函数内可以直接修改内容（无需 global）
# 【嵌套作用域】想改外层函数的变量，必须用 nonlocal 声明
# =====================================================================


# ---------------------------------------------------------------------
# 一、不可变类型的全局变量：需要用 global 才能修改
# ---------------------------------------------------------------------
print("=" * 40)
print("一、修改不可变类型的全局变量")
print("=" * 40)

a = 10                           # 全局变量（不可变类型）

def modify_a():
    # global 声明 a 指向"全局变量"，而不是新建一个局部变量
    global a
    a = 100
    print(a)                     # 输出：100

modify_a()
print(a)                         # 输出：100（全局变量真的被改了）


# ---------------------------------------------------------------------
# 二、可变类型的全局变量：可以直接修改内容
# ---------------------------------------------------------------------
print("=" * 40)
print("二、修改可变类型的全局变量")
print("=" * 40)

b = [1, 2, 3]                    # 全局变量（可变类型）

def modify_b():
    b[0] = 100                   # 只改"内容"，不改指向 → 不需要 global
    print(b)                     # 输出：[100, 2, 3]

modify_b()
print(b)                         # 输出：[100, 2, 3]


# ---------------------------------------------------------------------
# 三、嵌套作用域的变量：需要用 nonlocal 才能修改
# ---------------------------------------------------------------------
print("=" * 40)
print("三、修改嵌套作用域的变量")
print("=" * 40)

def modify_c():
    c = 200                      # 嵌套作用域变量

    def modify_d():
        # nonlocal 声明 c 指向"外层函数的变量"，而不是新建局部变量
        nonlocal c
        c = 2000
        print(c)                 # 输出：2000

    modify_d()
    print(c)                     # 输出：2000（外层函数的 c 被改了）

modify_c()