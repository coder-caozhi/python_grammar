# =====================================================================
# 07. lambda 表达式
# ---------------------------------------------------------------------
# 【语法】lambda 参数1, 参数2: 表达式
# 【特点】匿名函数，只能写一行表达式，自动返回表达式的结果
# 【场景】常配合 map / filter / sorted 等函数"临时"使用
# 【对比】sort() 原地排序、无返回值；sorted() 返回新列表
# =====================================================================


# 定义一个列表
my_list = [1, 2, -3, 4, -5]


# ---------------------------------------------------------------------
# 一、map + lambda：对每个元素做同样的处理
# ---------------------------------------------------------------------
print("=" * 40)
print("一、map + lambda")
print("=" * 40)

# map(函数, 可迭代对象)：把函数依次作用到每个元素上
# 注意：map 返回的是迭代器，要用 list() 转成列表才能看到结果
my_list2 = list(map(lambda a: a ** 2, my_list))
print(my_list2)                  # 输出：[1, 4, 9, 16, 25]

# ---------------------------------------------------------------------
# 二、filter + lambda：筛选出符合条件的元素
# ---------------------------------------------------------------------
print("=" * 40)
print("二、filter + lambda")
print("=" * 40)

# filter(函数, 可迭代对象)：函数返回 True 的元素保留，False 的丢弃
my_list3 = list(filter(lambda x: x % 2 == 0, my_list))
print(my_list3)                  # 输出：[2, 4]


# ---------------------------------------------------------------------
# 三、sort 与 sorted 的区别
# ---------------------------------------------------------------------
print("=" * 40)
print("三、sort 与 sorted")
print("=" * 40)

# sort()：原地排序，直接改原列表，没有返回值
my_list.sort()
print(my_list)                   # 输出：[-5, -3, 1, 2, 4]

# sorted()：排序后返回"新列表"，原列表不变；reverse=True 表示降序
# 注意：这里按数值大小排序，不是按原来的顺序
my_list4 = sorted(my_list, reverse=True)
print(my_list4)                  # 输出：[4, 2, 1, -3, -5]


# ---------------------------------------------------------------------
# 四、sorted + key + lambda：按"自定义规则"排序
# ---------------------------------------------------------------------
print("=" * 40)
print("四、sorted + key + lambda")
print("=" * 40)

# key=lambda x: abs(x)：先对每个元素取绝对值，再按绝对值降序排序
my_list5 = sorted(my_list, key=lambda x: abs(x), reverse=True)
print(my_list5)                  # 输出：[-5, 4, -3, 2, 1]