# =====================================================================
# 04. 嵌套调用
# ---------------------------------------------------------------------
# 【概念】函数 A 内部调用了函数 B，就叫嵌套调用
# 【执行顺序】"先进后出"：b 入栈 → a 入栈 → a 出栈 → b 出栈
# =====================================================================


# ---------------------------------------------------------------------
# 一、定义两个函数
# ---------------------------------------------------------------------
def a():
    print("a方法入栈")
    print("执行a方法中的逻辑")
    print("a方法出栈")


def b():
    print("b方法入栈")
    a()                          # b 内部调用 a → 嵌套调用
    print("b方法出栈")


# ---------------------------------------------------------------------
# 二、调用函数 b，观察执行顺序
# ---------------------------------------------------------------------
print("=" * 40)
print("二、调用函数 b")
print("=" * 40)

# 输出顺序：b方法入栈 → a方法入栈 → 执行a方法中的逻辑 → a方法出栈 → b方法出栈
b()