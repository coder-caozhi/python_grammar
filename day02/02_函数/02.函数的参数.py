# =====================================================================
# 02. 函数的参数
# ---------------------------------------------------------------------
# 【位置参数】  实参和形参按"顺序"一一对应
# 【关键字参数】调用时写 形参名=值，可以不按顺序
# 【默认参数】  def f(a, b=默认值)：不传就用默认值
# 【可变参数】  *args → 打包成元组；**kwargs → 打包成字典
# 【顺序规则】  位置参数 → 默认参数 → *args → 关键字-only → **kwargs
# =====================================================================


# 声明函数：形参 name、age
def get_info(name, age):
    print(f"您的姓名是：{name}，您今年{age}岁了")


# ---------------------------------------------------------------------
# 一、位置参数：实参的个数与位置必须与形参一致
# ---------------------------------------------------------------------
print("=" * 40)
print("一、位置参数")
print("=" * 40)

get_info("吴亦凡", 35)            # 输出：您的姓名是：吴亦凡，您今年35岁了
get_info(27, "蔡徐坤")            # 输出：您的姓名是：27，您今年蔡徐坤岁了（顺序不能乱）


# ---------------------------------------------------------------------
# 二、关键字参数：调用时写 形参名=值，顺序可以打乱
# ---------------------------------------------------------------------
print("=" * 40)
print("二、关键字参数")
print("=" * 40)

get_info(age=24, name="王飞龙")   # 输出：您的姓名是：王飞龙，您今年24岁了


# ---------------------------------------------------------------------
# 三、默认参数：可传可不传，不传就用默认值
# ---------------------------------------------------------------------
print("=" * 40)
print("三、默认参数")
print("=" * 40)

# 语法：def 函数名(参数, 参数=默认值)
# 注意：默认参数必须写在普通参数后面
def get_user(name, age, gender="男"):
    print(f"您的姓名是：{name}，您的年龄是：{age}，您的性别是：{gender}")

get_user("刘备", 30)              # 不传 gender → 使用默认值"男"
get_user("孙尚香", 16, "女")      # 传了 gender → 使用传入的"女"


# ---------------------------------------------------------------------
# 四、可变参数 *args：多个位置实参被打包成一个元组
# ---------------------------------------------------------------------
print("=" * 40)
print("四、可变参数 *args")
print("=" * 40)

# 语法：def 函数名(*args)
# 说明：*args 后面如果还有普通参数，那些参数必须用"关键字"传参
def fun(a, *args):
    print(f"第一个参数是：{a}")
    print(f"剩下的参数是：{args}")

fun(1, 2, 3, 4, 5)
# 输出：第一个参数是：1
#      剩下的参数是：(2, 3, 4, 5)


# ---------------------------------------------------------------------
# 五、关键字-only 参数：*args 后面的参数必须用关键字传参
# ---------------------------------------------------------------------
print("=" * 40)
print("五、关键字-only 参数")
print("=" * 40)

def fun1(a, *args, b):
    print(f"第一个参数是：{a}")
    print(f"剩下的参数是：{args}")
    print(f"可变参数后面的参数值是：{b}")

fun1(1, 2, 3, 4, 5, b=6)          # b 只能用 b=6 传，不能按位置传


# ---------------------------------------------------------------------
# 六、可变参数 **kwargs：多个关键字实参被打包成一个字典
# ---------------------------------------------------------------------
print("=" * 40)
print("六、可变参数 **kwargs")
print("=" * 40)

# 语法：def 函数名(**kwargs)
# 注意：**kwargs 必须放在参数列表最后
def fun2(a, **kwargs):
    print(f"第一个参数是：{a}")
    print(f"剩下的参数是：{kwargs}")

fun2(1, name="赵云", role="五虎上将")
# 输出：第一个参数是：1
#      剩下的参数是：{'name': '赵云', 'role': '五虎上将'}

# 错误示例：**kwargs 后面不能再有参数
# def fun3(a, **kwargs, b):  # 会报语法错误


