# =====================================================================
# 03. 集合
# ---------------------------------------------------------------------
# 【特点】    无序、可变、不可重复、值类型不限
# 【创建方式】1. 使用大括号{}
#             （注意：空集合只能用 set()，{} 创建的是空"字典"）
#             2. 使用 set() 函数
# 【获取元素】只能遍历（无序，没有索引下标）
# 【场景】    去重、集合运算（交 / 并 / 差 / 对称差）
# =====================================================================


# ---------------------------------------------------------------------
# 一、使用 {} 创建集合
# ---------------------------------------------------------------------
print("=" * 40)
print("一、使用 {} 创建集合")
print("=" * 40)

my_set = {1, 1, 2, 3, 4}          # 重复的 1 会被自动去掉
print(my_set)                     # 输出：{1, 2, 3, 4}
print(type(my_set))               # 输出：<class 'set'>


# ---------------------------------------------------------------------
# 二、空集合必须用 set() 创建
# ---------------------------------------------------------------------
print("=" * 40)
print("二、空集合")
print("=" * 40)

# my_empty_set = {}               # 错误示范：{} 创建的是空"字典"
print(my_empty_set)               # 输出：set()

my_empty_set = set()              # 正确：用 set() 创建空集合
print(my_empty_set)               # 输出：set()
print(type(my_empty_set))         # 输出：<class 'set'>


# ---------------------------------------------------------------------
# 三、使用 set() 函数创建集合（常用于去重）
# ---------------------------------------------------------------------
print("=" * 40)
print("三、使用 set() 函数创建集合")
print("=" * 40)

my_set2 = set([5, 5, 6, 6, 7, 8, 9])   # 列表中的重复元素被自动去重
print(my_set2)                    # 输出：{5, 6, 7, 8, 9}
print(type(my_set2))              # 输出：<class 'set'>


# ---------------------------------------------------------------------
# 四、常用函数：增 / 删 / 清空
# ---------------------------------------------------------------------
print("=" * 40)
print("四、常用函数")
print("=" * 40)

my_set.add(5)                     # 添加单个元素
print(my_set)                     # 输出：{1, 2, 3, 4, 5}

my_set.update([6, 6, 7, 7])       # 添加多个元素（同样会自动去重）
print(my_set)                     # 输出：{1, 2, 3, 4, 5, 6, 7}

print(my_set.pop())               # 随机弹出一个元素，并把该元素返回
print(my_set)                     # 输出：弹出后的剩余元素

# my_set.remove(4)                # 删除存在的元素
# my_set.remove(8)                # 删除不存在的元素会报错：KeyError
my_set.discard(8)                 # discard 删除不存在的元素也不会报错
print(my_set)

my_set.clear()                    # 清空集合
print(my_set)                     # 输出：set()


# ---------------------------------------------------------------------
# 五、集合运算：交 / 并 / 差 / 对称差
# ---------------------------------------------------------------------
print("=" * 40)
print("五、集合运算")
print("=" * 40)

my_set3 = {1, 2, 3, 4, 5}
my_set4 = {2, 3, 4, 5, 6}

print(my_set3 & my_set4)          # 交集：两个集合都有的元素 → {2, 3, 4, 5}
print(my_set3 | my_set4)          # 并集：合并后去重 → {1, 2, 3, 4, 5, 6}
print(my_set3 - my_set4)          # 差集：my_set3 有而 my_set4 没有 → {1}
print(my_set4 - my_set3)          # 差集：my_set4 有而 my_set3 没有 → {6}
print(my_set3 ^ my_set4)          # 对称差集：只在其中一个集合里 → {1, 6}
print(my_set4 ^ my_set3)          # 对称差集：结果与上面相同
