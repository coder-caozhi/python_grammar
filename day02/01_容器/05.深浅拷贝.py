# =====================================================================
# 05. 深浅拷贝
# ---------------------------------------------------------------------
# 【赋值】    a = b：两个名字指向"同一个对象"（内存地址相同）
# 【浅拷贝】  copy.copy()：新对象，但内部嵌套的对象仍是"共享"的
# 【深拷贝】  copy.deepcopy()：新对象，内部嵌套对象也递归复制，完全独立
# 【记忆点】  浅拷贝只复制"最外层"，深拷贝复制"全部"
# =====================================================================

import copy


# ---------------------------------------------------------------------
# 一、赋值：两个变量指向同一个对象
# ---------------------------------------------------------------------
print("=" * 40)
print("一、赋值")
print("=" * 40)

a = b = 10
print(id(a))                      # 输出：a 的内存地址
print(id(b))                      # 输出：与 a 完全相同（指向同一对象）


# ---------------------------------------------------------------------
# 二、浅拷贝：最外层是新的，内部嵌套对象仍共享
# ---------------------------------------------------------------------
print("=" * 40)
print("二、浅拷贝")
print("=" * 40)

my_list = [1, [2, 3]]
my_list2 = my_list.copy()         # 浅拷贝，等价于 copy.copy(my_list)
print(my_list)                    # 输出：[1, [2, 3]]
print(my_list2)                   # 输出：[1, [2, 3]]

print(id(my_list))                # 最外层地址不同：是两个不同的列表
print(id(my_list2))

# 修改最外层的值：互不影响
# my_list[0] = 10                 # my_list 会变，my_list2 不变

# 修改内部嵌套列表的值：两个都会变（因为内层对象是共享的）
my_list[1][0] = 200
print(my_list)                    # 输出：[1, [200, 3]]
print(my_list2)                   # 输出：[1, [200, 3]] ← 跟着一起变了！


# ---------------------------------------------------------------------
# 三、深拷贝：内部嵌套对象也复制，完全独立
# ---------------------------------------------------------------------
print("=" * 40)
print("三、深拷贝")
print("=" * 40)

my_list3 = copy.deepcopy(my_list) # 深拷贝
print(my_list)                    # 输出：[1, [200, 3]]
print(my_list3)                   # 输出：[1, [200, 3]]
print(id(my_list))                # 最外层地址不同
print(id(my_list3))

# 此时再修改 my_list 内部嵌套列表：my_list3 完全不受影响
my_list[1][0] = 300
print(my_list)                    # 输出：[1, [300, 3]]
print(my_list3)                   # 输出：[1, [200, 3]] ← 保持不变
